"""AsciiDoc emission for the IFE specification document.

One file per item, not one file per document. The narrative
(``spec/ife_spec.adoc``) pulls each in with Asciidoctor's native ``include::``,
so a section moves without dragging unrelated tables along and the document
never contains a hand-written offset. This is how Khronos assembles the Vulkan
specification from ``vk.xml``, and the reason no bespoke anchor syntax or
preprocessor exists here.

Emitted into ``generated_docs/``:

    layout/<BLOCK>.adoc          one block's header table
    layout/<BLOCK>_entry.adoc    that block's entry table, where it has one
    layout/primitive_<NAME>.adoc a shared prefix (file_header, block, array…)
    constants/<GROUP>.adoc       one enumeration, or the sentinel values
    provenance.adoc              schema and generator version of this build

Every table is a two-column-plus AsciiDoc table with a title, so the published
document gets numbered captions and cross-references for free.
"""
from __future__ import annotations

from typing import Any

from ..model.layout import BlockLayout, FieldLayout, LayoutResult, is_banner, parse_int, version_key

# Emitted paths are relative to the docs root; the narrative includes them by
# these names, so they are part of the contract with spec/ife_spec.adoc.
LAYOUT_DIR = "layout"
CONSTANTS_DIR = "constants"


def _banner() -> list[str]:
    return [
        "////",
        "Generated by `python3 -m generator` from spec/*.json — DO NOT EDIT BY HAND.",
        "Offsets and sizes are derived from field order and width, never stored.",
        "////",
        "",
    ]


def _type_column(field: FieldLayout) -> str:
    if field.kind == "enum":
        return f"enum `{field.type_name}`"
    if field.kind == "constant":
        return f"`{field.type_name}` = `{field.constant}`"
    return f"`{field.type_name}`"


def _cell(text: str) -> str:
    """A table cell: strip the newlines AsciiDoc would treat as a row break."""
    return " ".join(text.split()).replace("|", "\\|")


def _layout_table(title: str, fields: tuple[FieldLayout, ...]) -> list[str]:
    out = [
        f".{title}",
        '[cols="2,2,1,1,1,5",options="header",frame=all,grid=all]',
        "|===",
        "|Field |Type |Offset |Size |Optional |Description",
        "",
    ]
    for field in fields:
        # Optional == the spec's `nullable: true` — the offset may hold
        # NULL_OFFSET. Fields without the key are required.
        out.append(
            f"|`{field.name}` |{_type_column(field)} |{field.offset} |{field.size} "
            f"|{'Yes' if field.nullable else 'No'} |{_cell(field.description)}"
        )
    out += ["|===", ""]
    return out


def emit_block_layout(block: BlockLayout) -> str:
    """One block's header table, as its own includable file."""
    out = _banner()
    out += _layout_table(
        f"`{block.name}` header — {block.header_size} bytes"
        + (f", at byte 0 ({block.from_sof} B from start of file)" if block.from_sof is not None else "")
        + f", recovery tag `{block.recovery_tag}` (0x{block.recovery_value:04X})",
        block.header_fields,
    )
    return "\n".join(out)


def emit_entry_layout(block: BlockLayout) -> str:
    """One array block's entry table."""
    out = _banner()
    out += _layout_table(
        f"`{block.entry_name}` entry — {block.entry_size} bytes, "
        f"addressed by the array's stored `STRIDE`",
        block.entry_fields,
    )
    return "\n".join(out)


def emit_primitive_layout(primitive: Any) -> str:
    """A shared prefix every derived block carries."""
    out = _banner()
    inherits = f", extending `{primitive.extends}`" if primitive.extends else ""
    out += _layout_table(
        f"`{primitive.name}` primitive — {primitive.size} bytes{inherits}",
        primitive.fields,
    )
    return "\n".join(out)


def emit_constants_table(group_name: str, group: dict[str, Any], recovery_prefix: int) -> str:
    """One enumeration, or the statically defined values."""
    out = _banner()
    sentinels = group_name == "statically_defined_values"
    title = f"`{group_name}`"
    if not sentinels and group.get("underlying_type"):
        title += f" — `{group['underlying_type']}`"

    out += [
        f".{title}",
        '[cols="2,1,5",options="header",frame=all,grid=all]',
        "|===",
        "|Name |Value |Description",
        "",
    ]
    derived = group_name == "recovery_codes"
    index = 0
    for _, entries in sorted(group.get("ife_version", {}).items(), key=lambda kv: version_key(kv[0])):
        for name, raw in entries.items():
            entry = raw if isinstance(raw, dict) else {"value": raw}
            value = entry.get("value")
            if derived:
                # Tag values are derived from position, as the generator
                # assigns them; the document must show what is on the wire.
                display = f"0x{recovery_prefix + parse_int(value):04X}"
            elif isinstance(value, str) and value.lower().startswith("0x"):
                display = value
            elif value is None:
                display = ""
            else:
                display = str(parse_int(value))
            out.append(
                f"|`{name}` |{display} |{_cell(str(entry.get('description', '')))}"
            )
            index += 1
    out += ["|===", ""]
    return "\n".join(out)


def emit_provenance(document: dict[str, Any], generator_version: str) -> str:
    """What produced this document.

    A ratified specification that cannot be reproduced years later is not
    reproducible in any useful sense, and the generator is part of the standard
    now — not merely a build tool. So the published document states both the
    schema version and the generator that rendered it.
    """
    version = document.get("version", {})
    return "\n".join(
        _banner()
        + [
            "[cols=\"1,3\",frame=none,grid=rows]",
            "|===",
            f"|Specification version |{version.get('major', 0)}.{version.get('minor', 0)}",
            f"|Status |{document.get('status', 'draft')}",
            f"|Generator |{generator_version}",
            f"|Copyright |{document.get('copyright', '')}",
            f"|Licence |{document.get('license', '')}",
            "|===",
            "",
        ]
    )


def emit_documents(
    layout: LayoutResult, constants_doc: dict[str, Any], document: dict[str, Any],
    generator_version: str, recovery_prefix: int,
) -> dict[str, str]:
    """Every generated AsciiDoc file: relative path -> content."""
    out: dict[str, str] = {"provenance.adoc": emit_provenance(document, generator_version)}

    for primitive in layout.primitives.values():
        out[f"{LAYOUT_DIR}/primitive_{primitive.name}.adoc"] = emit_primitive_layout(primitive)

    for name, block in layout.blocks.items():
        out[f"{LAYOUT_DIR}/{name}.adoc"] = emit_block_layout(block)
        if block.entry_fields:
            out[f"{LAYOUT_DIR}/{name}_entry.adoc"] = emit_entry_layout(block)

    for group_name, group in constants_doc.items():
        if group_name in ("$schema", "spec") or is_banner(group_name):
            continue
        out[f"{CONSTANTS_DIR}/{group_name}.adoc"] = emit_constants_table(
            group_name, group, recovery_prefix
        )
    return out
