# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~ #
# IFE_Blocks.hpp / .cpp — typed handles over the wire
# ~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~~ #
# The header declares; the source defines. Both are produced from the same
# list of Member records in the same order, so the two files scroll in
# parallel — the structure IrisCodecExtension.hpp/.cpp has by hand, here by
# construction rather than by discipline.

_RESERVED_ACCESSORS = frozenset({"type", "recovery", "header_size", "entry_size", "size"})


class Member(NamedTuple):
    """One member function, rendered as a declaration and as a definition.

    Splitting the signature into parts is what lets the source qualify it
    (`Status FILE_HEADER::validate() const noexcept`) from the same record the
    header prints unqualified. Nothing may render one without the other.
    """

    doc: tuple[str, ...]        # /// lines, declaration only
    attrs: str                  # [[nodiscard]] and the like, declaration only
    ret: str
    name: str
    params: str
    quals: str                  # "const noexcept"
    body: tuple[str, ...]       # definition lines, without the braces


def _declare(out: list[str], member: Member, indent: str = "    ") -> None:
    out.extend(f"{indent}{line}" for line in member.doc)
    attrs = f"{member.attrs} " if member.attrs else ""
    out.append(f"{indent}{attrs}{member.ret} {member.name}({member.params}) {member.quals};")


def _define(out: list[str], owner: str, member: Member) -> None:
    out.append("")
    out.append(f"{member.ret} {owner}::{member.name}({member.params}) {member.quals} {{")
    out.extend(member.body)
    out.append("}")


def _accessor(field_name: str) -> str:
    """Accessor name for a field: the field name, lower-cased.

    RECOVERY would collide with the static `recovery` tag constant, so names
    clashing with a struct-scope member take a `_field` suffix. Mechanical, so
    the name is predictable from the spec.
    """
    name = field_name.lower()
    return f"{name}_field" if name in _RESERVED_ACCESSORS else name


def _version_of(since: str) -> int:
    major, minor = version_key(since)
    return (major << 16) | minor


def _read_expression(field: FieldLayout, vtable: str, types: dict[str, Any]) -> tuple[str, str]:
    """(return type, expression) for reading one field through IFE_Bytes."""
    at = f"__base + __offset + ::IFE::vtables::{vtable}::offset::{field.name}"
    if field.kind == "enum":
        enum = f"::IFE::constants::{_pascal(field.type_name)}"
        underlying = _cpp_of(field.type_name, types) if field.type_name in types else field.cpp_type
        return enum, f"static_cast<{enum}>(::IFE::load<{underlying}>({at}))"
    canonical = _canonical_type(field.type_name, types)
    if canonical == "u24":
        return "std::uint32_t", f"::IFE::load_u24({at})"
    if canonical == "u40":
        return "std::uint64_t", f"::IFE::load_u40({at})"
    if canonical == "f16":
        return "float", f"::IFE::load_f16({at})"
    return field.cpp_type, f"::IFE::load<{field.cpp_type}>({at})"


def _field_members(
    fields: tuple[FieldLayout, ...],
    vtable: str,
    types: dict[str, Any],
    stride_gated: bool = False,
) -> list[Member]:
    """One Member per readable field, in wire order."""
    members: list[Member] = []
    for field in fields:
        if field.kind == "constant":
            continue  # always holds its sentinel; validated, never read
        doc = tuple(f"/// {line}" for line in field.description.splitlines() if line.strip())

        if field.points_to:
            target = field.points_to
            note = (
                "Empty when the offset is NULL_OFFSET."
                if field.nullable
                else "Required: never NULL_OFFSET in a valid file."
            )
            body = [
                f"    const ::IFE::Offset __at = ::IFE::load<::IFE::Offset>(",
                f"        __base + __offset + ::IFE::vtables::{vtable}::offset::{field.name});",
            ]
            if field.nullable:
                body.append(f"    if (__at == ::IFE::constants::NULL_OFFSET) return {target}{{}};")
            body.append(f"    return {target}{{__base, __at, __size, __version}};")
            members.append(Member(
                doc=doc + (f"/// Handle to the {target} block this offset references. {note}",),
                attrs="[[nodiscard]]", ret=target, name=_accessor(field.name),
                params="", quals="const noexcept", body=tuple(body),
            ))
            continue

        cpp, expression = _read_expression(field, vtable, types)
        if field.since != "1.0":
            guard = f"__version < {_version_of(field.since):#010x}u"
            if stride_gated:
                guard += (
                    f"\n        || __stride < ::IFE::vtables::{vtable}::offset::{field.name}"
                    f" + ::IFE::vtables::{vtable}::size::{field.name}"
                )
            members.append(Member(
                doc=doc + (f"/// Added in {field.since}; empty when the file predates it.",),
                attrs="[[nodiscard]]", ret=f"std::optional<{cpp}>", name=_accessor(field.name),
                params="", quals="const noexcept",
                body=(f"    if ({guard}) return std::nullopt;", f"    return {expression};"),
            ))
        else:
            members.append(Member(
                doc=doc, attrs="[[nodiscard]]", ret=cpp, name=_accessor(field.name),
                params="", quals="const noexcept", body=(f"    return {expression};",),
            ))
    return members


def _version_boundaries(fields: tuple[FieldLayout, ...]) -> dict[int, str]:
    """Index -> version whose last readable field sits there."""
    marks: dict[int, str] = {}
    readable = [f for f in fields if f.kind != "constant"]
    for i, field in enumerate(readable):
        if i + 1 == len(readable) or readable[i + 1].since != field.since:
            marks[i] = field.since
    return marks


def _validate_member(name: str, block: Any, layout: LayoutResult) -> Member:
    """The block's own structural checks, in the order v1 performs them.

    Reproduces DATA_BLOCK::validate_offset (IrisCodecExtension.cpp:778-803) and
    the array bounds check from LAYER_EXTENTS::validate_full (:1641-1686).
    Deliberately absent is anything semantic: FILE_SIZE agreeing with the size
    the OS reports is a fact about the file, not the layout, and belongs to the
    runtime.
    """
    primitive = layout.primitives[block.primitive]
    vt = f"::IFE::vtables::{name}"
    body: list[str] = [
        "    if (!*this)",
        '        return {Check::NOT_CONSTRUCTED, type, "", __offset, __size, __offset};',
    ]
    prim_vt = f"::IFE::vtables::{block.primitive}"
    by_name = {f.name: f for f in primitive.fields}
    if "VALIDATION" in by_name:
        body += [
            "    // A block stores its own offset, so a pointer that landed here can",
            "    // prove it landed where it meant to.",
            "    if (const ::IFE::Offset __v = validation(); __v != __offset)",
            '        return {Check::BAD_VALIDATION, type, "VALIDATION", __v, __offset, __offset};',
        ]
    for field in primitive.fields:
        if field.kind == "constant":
            body += [
                f"    if (const auto __c = ::IFE::load<{field.cpp_type}>(",
                f"            __base + __offset + {prim_vt}::offset::{field.name});",
                f"        __c != ::IFE::constants::{field.constant})",
                f'        return {{Check::BAD_CONSTANT, type, "{field.name}", __c,',
                f"                ::IFE::constants::{field.constant}, __offset}};",
            ]
    body += [
        "    if (const auto __r = recovery_field(); __r != recovery)",
        '        return {Check::BAD_RECOVERY, type, "RECOVERY",',
        "                static_cast<std::uint64_t>(__r),",
        "                static_cast<std::uint64_t>(recovery), __offset};",
    ]
    if _has_count(block, layout):
        if block.entry_fields:
            floor = block.entry_sizes[0][1] if block.entry_sizes else block.entry_size
            body += [
                "",
                "    // The stride the encoder wrote must at least hold the entry this",
                "    // build knows; a wider one is a later version and is fine.",
                f"    if (const std::uint16_t __st = stride(); __st < {floor})",
                f'        return {{Check::BAD_STRIDE, type, "STRIDE", __st, {floor}, __offset}};',
            ]
            span = "static_cast<std::uint64_t>(stride()) * count()"
        else:
            body += ["", "    // A byte array stores no stride; its stride is one by definition."]
            span = "static_cast<std::uint64_t>(count())"
        body += [
            "",
            "    // Expressed as a subtraction so the multiplication cannot wrap:",
            "    // u16 * u32 fits a u64 comfortably.",
            "    const ::IFE::Offset __begin = entries_begin();",
            f"    const std::uint64_t __span = {span};",
            "    if (__begin > __size || __span > __size - __begin)",
            '        return {Check::ARRAY_OVERRUN, type, "COUNT", __span,',
            "                __size - (__begin > __size ? __size : __begin), __offset};",
        ]
    body.append("    return {};")
    return Member(
        doc=("/// Structural checks on this block alone. Never allocates or throws.",),
        attrs="[[nodiscard]]", ret="Status", name="validate", params="",
        quals="const noexcept", body=tuple(body),
    )


def _validate_deep_member(name: str, block: Any) -> Member:
    """Recurse the offset graph. Successor to v1's hand-threaded validate_full.

    v1 chained each block's check into its children by hand (:869-900), which
    is why a block added later is easy to forget. Here the walk is derived from
    `points_to`, so every edge in the schema is followed by construction —
    including edges leaving array *entries*, which a header-only walk would
    skip and which is exactly where IMAGE_BYTES and ANNOTATION_BYTES hang.
    """
    body: list[str] = [
        "    if (const Status __s = validate(); !__s) return __s;",
        "    if (__path.contains(__offset))",
        '        return {Check::CYCLE, type, "", __offset, 0, __offset};',
        "    if (!__path.push(__offset))",
        '        return {Check::CYCLE, type, "", __path.depth, MAX_BLOCK_DEPTH, __offset};',
    ]

    def walk(field, source: str, indent: str) -> list[str]:
        handle = f"__t_{field.name.lower()}"
        lines = [f"{indent}{{", f"{indent}    const auto {handle} = {source};"]
        if field.nullable:
            lines += [
                f"{indent}    // Optional: NULL_OFFSET means absent and is legal; any",
                f"{indent}    // other unusable value is not.",
                f"{indent}    if ({handle}.__offset != ::IFE::constants::NULL_OFFSET) {{",
            ]
        else:
            lines.append(f"{indent}    {{")
        inner = indent + "        "
        lines += [
            f"{inner}if (!{handle})",
            f'{inner}    return {{Check::OUT_OF_BOUNDS, type, "{field.name}",',
            f"{inner}            {handle}.__offset, __size, __offset}};",
            f"{inner}if (const Status __s = {handle}.validate_deep(__path); !__s) return __s;",
            f"{indent}    }}",
            f"{indent}}}",
        ]
        return lines

    for field in (f for f in block.header_fields if f.points_to):
        body += walk(field, f"{_accessor(field.name)}()", "    ")
    entry_edges = [f for f in block.entry_fields if f.points_to]
    if entry_edges:
        body += ["", "    // Edges that leave from entries, one per entry.",
                 "    for (std::uint32_t __i = 0; __i < count(); ++__i) {",
                 "        const auto __e = entry(__i);"]
        for field in entry_edges:
            body += walk(field, f"__e.{_accessor(field.name)}()", "        ")
        body.append("    }")
    body += ["    __path.pop();", "    return {};"]
    return Member(
        doc=("/// validate(), then every block this one reaches, transitively.",),
        attrs="[[nodiscard]]", ret="Status", name="validate_deep",
        params="VisitPath& __path", quals="const noexcept", body=tuple(body),
    )


_STATUS_PREAMBLE = """
// ---- validation vocabulary ----
// Generated validators never allocate, never throw and never format a string.
// They report a code plus the operands v1 interpolated into its messages
// (IrisCodecExtension.cpp:784-800) and leave the wording to the runtime, which
// has the JSON descriptions and is not on the hot path.

enum class Check : std::uint8_t {
    OK = 0,
    NOT_CONSTRUCTED,   ///< no base pointer, null offset, or header past EOF
    OUT_OF_BOUNDS,     ///< an offset field points outside the file
    BAD_VALIDATION,    ///< VALIDATION does not equal the block's own offset
    BAD_RECOVERY,      ///< RECOVERY is not this block's tag
    BAD_CONSTANT,      ///< a constant field does not hold its sentinel
    BAD_STRIDE,        ///< STRIDE is zero, or narrower than the entry it must hold
    ARRAY_OVERRUN,     ///< the entry run extends past the end of the file
    VERSION_TOO_NEW,   ///< reserved for the runtime; see below
    CYCLE,             ///< an offset chain returns to a block already on the path
    CONFORMANCE,       ///< a normative clause was violated; only the conformance layer raises this
};

/// Everything needed to describe a failure, unformatted.
struct Status {
    Check         code     = Check::OK;
    const char*   block    = "";
    const char*   field    = "";
    std::uint64_t found    = 0;
    std::uint64_t expected = 0;
    ::IFE::Offset at       = 0;

    constexpr explicit operator bool() const noexcept { return code == Check::OK; }
};

/// A newer file is never a structural failure: append-only guarantees its 1.0
/// prefix is readable, so VERSION_TOO_NEW is never returned by a generated
/// validator. It exists for the runtime to raise as a warning, matching v1
/// (IrisCodecExtension.cpp:853-865), which warns and continues.

inline constexpr std::size_t MAX_BLOCK_DEPTH = 16;

/// The chain of offsets from the root to the block being checked.
///
/// Cycle detection needs the *ancestry*, not every block ever seen: a file may
/// hold thousands of annotations each with its own byte array, all legitimate
/// separate visits, and a global set would reject the second of two entries
/// pointing at one target. A cycle is an offset that reappears on the current
/// path, bounded by the block graph's depth.
struct VisitPath {
    ::IFE::Offset entries[MAX_BLOCK_DEPTH]{};
    std::size_t   depth = 0;

    [[nodiscard]] constexpr bool contains(::IFE::Offset __o) const noexcept {
        for (std::size_t __i = 0; __i < depth; ++__i)
            if (entries[__i] == __o) return true;
        return false;
    }
    [[nodiscard]] constexpr bool push(::IFE::Offset __o) noexcept {
        if (depth == MAX_BLOCK_DEPTH) return false;
        entries[depth++] = __o;
        return true;
    }
    constexpr void pop() noexcept { if (depth) --depth; }
};
"""


def _block_members(
    name: str, block: Any, layout: LayoutResult, types: dict[str, Any]
) -> list[Member]:
    """Every member of one block struct, declaration order == definition order."""
    primitive = layout.primitives[block.primitive]
    own = tuple(f for f in block.header_fields if f not in primitive.fields)
    members = _field_members(own, name, types)
    members.append(_validate_member(name, block, layout))
    members.append(_validate_deep_member(name, block))
    return members


def _entry_members(name: str, block: Any, types: dict[str, Any]) -> list[Member]:
    return _field_members(block.entry_fields, f"{name}::entry", types, stride_gated=True)


def _emit_primitive_bases(out: list[str], layout: LayoutResult, types: dict[str, Any]) -> None:
    """The schema's primitive hierarchy, as plain structs.

    Not templates: v1 keeps DATA_BLOCK a plain base by passing the per-type
    data down as arguments (IrisCodecExtension.hpp:405 —
    validate_offset(__base, type, recovery)) rather than encoding it in the
    type. The same trick applies to the bounds check, so `fits` takes the
    derived block's header_size instead of the base having to know it. Plain
    bases are what let every body live in the .cpp.
    """
    out.append("")
    out.append("namespace primitives {")
    out.append("// Nested so a primitive may share a name with the block that uses it.")
    out.append("// In vtables those are namespaces and merge harmlessly; here they are")
    out.append("// structs, and FILE_HEADER (the root primitive) would otherwise collide")
    out.append("// with FILE_HEADER (the block deriving from it).")
    for primitive in layout.primitives.values():
        base = f" : public {primitive.extends}" if primitive.extends else ""
        out.append("")
        out.extend(_comment(primitive.description))
        out.append(f"struct {primitive.name}{base} {{")
        if primitive.extends is None:
            out += [
                "    const ::IFE::BYTE* __base    = nullptr;",
                "    ::IFE::Offset      __offset  = ::IFE::constants::NULL_OFFSET;",
                "    ::IFE::Size        __size    = 0;   ///< total file size",
                "    std::uint32_t      __version = 0;   ///< major<<16 | minor, from FILE_HEADER",
                "",
                "    /// Whether a block of `__header_size` bytes fits here. Stricter than",
                "    /// v1's operator bool (IrisCodecExtension.cpp:774-777), which checks",
                "    /// only that the offset is in range: requiring the whole header to fit",
                "    /// makes a truncated file fail at construction rather than mid-read.",
                "    [[nodiscard]] constexpr bool fits(::IFE::Size __header_size) const noexcept {",
                "        return __base != nullptr",
                "            && __offset != ::IFE::constants::NULL_OFFSET",
                "            && __offset + __header_size <= __size;",
                "    }",
            ]
        inherited = layout.primitives[primitive.extends].fields if primitive.extends else ()
        introduced = tuple(f for f in primitive.fields if f not in inherited)
        for member in _field_members(introduced, primitive.name, types):
            out.append("")
            _declare(out, member)
        # Whichever primitives carry a COUNT are the ones with something after
        # the header to address. Keyed on the field rather than on the
        # primitive's name, which the schema is free to change.
        if any(f.name == "COUNT" for f in primitive.fields):
            out += [
                "",
                "    /// Where the entry run starts. Takes the derived block's header size",
                "    /// for the same reason `fits` does.",
                "    [[nodiscard]] constexpr ::IFE::Offset entries_at(",
                "            ::IFE::Size __header_size) const noexcept {",
                "        return __offset + __header_size;",
                "    }",
            ]
        out.append("};")
    out.append("")
    out.append("}  // namespace primitives")


# ---------------------------------------------------------------------------
# Writers. Per block: a CreateInfo carrying what only the caller knows,
# a size_of, and a store. Replaces v1's 22 hand-written free functions -- 9
# SIZE_* and 13 STORE_* -- none of which survive.
# ---------------------------------------------------------------------------

# The primitive fields are the machine-written prefix: a caller never supplies
# one, because store() derives each from something it already has. Keyed by
# name deliberately -- the primitive vocabulary is closed (four primitives,
# five distinct fields) and declared in the schema, so an unrecognised one
# means the schema grew a concept the writer does not know how to fill. That
# raises rather than emitting a store() that silently leaves bytes unwritten.
_PRIMITIVE_FIELDS = frozenset({"MAGIC", "VALIDATION", "RECOVERY", "STRIDE", "COUNT"})


def _create_info(block_name: str) -> str:
    return f"{_pascal(block_name)}CreateInfo"


def _entry_struct(entry_name: str) -> str:
    """LAYER_EXTENT -> LayerExtentEntry, IMAGE_ENTRY -> ImageEntry."""
    stem = entry_name[: -len("_ENTRY")] if entry_name.endswith("_ENTRY") else entry_name
    return f"{_pascal(stem)}Entry"


def _writer_type(field: FieldLayout, types: dict[str, Any]) -> str:
    """The type a caller supplies for one field -- the mirror of _read_expression."""
    if field.kind == "enum":
        return f"::IFE::constants::{_pascal(field.type_name)}"
    canonical = _canonical_type(field.type_name, types)
    if canonical == "u24":
        return "std::uint32_t"
    if canonical == "u40":
        return "std::uint64_t"
    if canonical == "f16":
        return "float"
    return field.cpp_type


def _writer_default(field: FieldLayout) -> str:
    """Offsets default to NULL_OFFSET, everything else to a value-initialised zero.

    Every points_to member gets NULL_OFFSET, not only the nullable ones: zero
    is a legal offset (it is the file header), so an offset left unset would
    otherwise point somewhere plausible instead of somewhere obviously wrong.
    """
    return "::IFE::constants::NULL_OFFSET" if field.points_to else "{}"


def _write_expression(
    field: FieldLayout, vtable: str, value: str, types: dict[str, Any], base: str
) -> str:
    """One store through IFE_Bytes. The exact inverse of _read_expression."""
    at = f"{base} + ::IFE::vtables::{vtable}::offset::{field.name}"
    if field.kind == "enum":
        underlying = _cpp_of(field.type_name, types) if field.type_name in types else field.cpp_type
        return f"::IFE::store<{underlying}>({at}, static_cast<{underlying}>({value}));"
    canonical = _canonical_type(field.type_name, types)
    if canonical == "u24":
        return f"::IFE::store_u24({at}, {value});"
    if canonical == "u40":
        return f"::IFE::store_u40({at}, {value});"
    if canonical == "f16":
        return f"::IFE::store_f16({at}, {value});"
    return f"::IFE::store<{field.cpp_type}>({at}, {value});"


def _caller_fields(block: Any, layout: LayoutResult) -> tuple[FieldLayout, ...]:
    """The header fields a CreateInfo carries: this block's own, minus constants."""
    primitive = layout.primitives[block.primitive]
    own = tuple(f for f in block.header_fields if f not in primitive.fields)
    return tuple(f for f in own if f.kind != "constant")


def _emit_create_infos(out: list[str], layout: LayoutResult, types: dict[str, Any]) -> None:
    """Entry PODs and CreateInfo structs, in block order."""
    for name, block in layout.blocks.items():
        if block.entry_fields:
            entry = _entry_struct(block.entry_name or f"{name}_ENTRY")
            out.append("")
            out.append(f"/// One entry to write into {name}. Members are the spec's field")
            out.append("/// names verbatim, so a caller reads the specification directly.")
            out.append(f"struct {entry} {{")
            for field in block.entry_fields:
                if field.kind == "constant":
                    continue
                for line in field.description.splitlines():
                    if line.strip():
                        out.append(f"    /// {line}")
                out.append(
                    f"    {_writer_type(field, types)} {field.name} = {_writer_default(field)};"
                )
            out.append("};")

        out.append("")
        out.extend(_comment(block.description))
        out.append(f"struct {_create_info(name)} {{")
        for field in _caller_fields(block, layout):
            for line in field.description.splitlines():
                if line.strip():
                    out.append(f"    /// {line}")
            out.append(f"    {_writer_type(field, types)} {field.name} = {_writer_default(field)};")
        if block.entry_fields:
            entry = _entry_struct(block.entry_name or f"{name}_ENTRY")
            out += [
                f"    /// The entries themselves; `count` of them. store() writes STRIDE",
                f"    /// and COUNT from these -- they are never supplied.",
                f"    const {entry}* entries = nullptr;",
                "    std::uint32_t   count   = 0;",
            ]
        elif _is_blob(block, layout):
            out += [
                "    /// The byte run. What it means is not this layer's business: the",
                "    /// slicing comes from a sizes array elsewhere.",
                "    const ::IFE::BYTE* bytes = nullptr;",
                "    ::IFE::Size        count = 0;",
            ]
        out.append("};")


def _emit_validation_hooks(out: list[str], layout: LayoutResult) -> None:
    """The dispatch point for the optional conformance layer, present from day one."""
    out += [
        "",
        "/// The optional, runtime-attached spec-conformance layer.",
        "///",
        "/// The conformance layer implements what sits behind these pointers; this is the call site,",
        "/// and it is emitted now because adding a dispatch point later would break",
        "/// the ABI. Null when no layer is attached, which is what a shipped product",
        "/// runs: the cost is one predictable branch per store, never a search.",
        "///",
        "/// Borrowed from Vulkan: a separate library that need not be linked,",
        "/// attachment decided once at writer creation, diagnostics through a",
        "/// caller-registered callback so the layer never owns I/O policy, and a",
        "/// `next` pointer so a future tracing layer composes rather than competes.",
        "/// Not borrowed: the loader, trampolines and manifest discovery.",
        "struct ValidationHooks {",
        "    const ValidationHooks* next = nullptr;",
        "",
        "    /// Where a diagnostic goes. The layer formats; the caller decides what",
        "    /// I/O means.",
        "    void (*diagnostic)(const char* __message, void* __user) = nullptr;",
        "    void* user = nullptr;",
        "",
        "    // One per block. Each receives the same CreateInfo and target offset",
        "    // store() was given -- the layer validates at the API boundary, as a",
        "    // Vulkan layer does, never against generated internals.",
    ]
    for name in layout.blocks:
        out.append(
            f"    Status (*{name})(const {_create_info(name)}&, ::IFE::Offset,"
            f" const ValidationHooks*) = nullptr;"
        )
    out.append("};")


def _writer_signature(name: str, declaration: bool) -> tuple[str, str]:
    """(size_of, store) signatures.

    The declaration carries `[[nodiscard]]` and defaults `__hooks`; the
    definition may do neither -- an attribute after `inline` is not a place the
    grammar allows one, and a default argument may be stated once.
    """
    info = _create_info(name)
    attrs = "[[nodiscard]] " if declaration else ""
    default = " = nullptr" if declaration else ""
    indent = " " * len("Status store(") if declaration else " " * len("IFE_BLOCKS_INLINE Status store(")
    return (
        f"{attrs}::IFE::Size size_of(const {info}& __info) noexcept",
        f"Status store(::IFE::BYTE* __base, ::IFE::Offset __offset, const {info}& __info,\n"
        f"{indent}const ValidationHooks* __hooks{default}) noexcept",
    )


def _emit_writer_decls(out: list[str], layout: LayoutResult) -> None:
    for name, block in layout.blocks.items():
        size_of, store = _writer_signature(name, declaration=True)
        out.append("")
        out.append(f"// ---- {name} ----")
        if block.entry_fields:
            out.append("/// Header plus `count` entries at the stride this build writes.")
        elif _is_blob(block, layout):
            out.append("/// Header plus the byte run.")
        else:
            out.append("/// The header. A payload the schema does not describe -- IMAGE_BYTES'")
            out.append("/// label and stream, TILE_PIXEL_DATA -- is the runtime's to place.")
        out.append(f"{size_of};")
        out.append("/// Writes the block, then validates what it wrote. The machine-written")
        out.append("/// fields (VALIDATION, RECOVERY, MAGIC, STRIDE, COUNT) are never taken")
        out.append("/// from the caller.")
        out.append(f"{store};")


def _emit_writer_defs(
    out: list[str], layout: LayoutResult, types: dict[str, Any]
) -> None:
    for name, block in layout.blocks.items():
        primitive = layout.primitives[block.primitive]
        vt = f"::IFE::vtables::{name}"
        size_of, store = _writer_signature(name, declaration=False)

        out.append("")
        out.append(f"// ---- {name} ----")
        out.append("")
        out.append(f"IFE_BLOCKS_INLINE {size_of} {{")
        if block.entry_fields:
            out.append(f"    return {vt}::header_size")
            out.append(
                f"         + static_cast<::IFE::Size>(__info.count) * {vt}::entry_size;"
            )
        elif _is_blob(block, layout):
            out.append(f"    return {vt}::header_size + __info.count;")
        else:
            out.append("    (void)__info;")
            out.append(f"    return {vt}::header_size;")
        out.append("}")

        out.append("")
        out.append(f"IFE_BLOCKS_INLINE {store} {{")
        out.append("    // The machine-written prefix, in wire order.")
        for field in primitive.fields:
            if field.name not in _PRIMITIVE_FIELDS:
                raise SpecError(
                    f"primitive {block.primitive!r} declares field {field.name!r}, which the "
                    f"writer emitter does not know how to fill; teach _PRIMITIVE_FIELDS "
                    f"what supplies it before adding it to the schema"
                )
            if field.kind == "constant":
                value = f"::IFE::constants::{field.constant}"
            elif field.name == "VALIDATION":
                value = "__offset"
            elif field.name == "RECOVERY":
                # _write_expression supplies the cast to the underlying type.
                value = f"{name}::recovery"
            elif field.name == "STRIDE":
                value = f"{vt}::entry_size"
            else:  # COUNT
                value = f"static_cast<{field.cpp_type}>(__info.count)"
            # Through the primitive's namespace: it is where an inherited
            # field's offset is declared, and the shared readers use the same
            # constant, so writer and reader cannot name different bytes.
            out.append(
                "    "
                + _write_expression(
                    field,
                    _owning_namespace(name, block, field, layout),
                    value,
                    types,
                    "__base + __offset",
                )
            )

        caller = _caller_fields(block, layout)
        if caller:
            out.append("")
            out.append("    // What only the caller knows.")
            for field in caller:
                out.append(
                    "    "
                    + _write_expression(
                        field, name, f"__info.{field.name}", types, "__base + __offset"
                    )
                )

        if block.entry_fields:
            out += [
                "",
                "    // Entries step by the stride this build writes, which is what was",
                "    // just stored in STRIDE -- a reader steps by the stride it finds.",
                f"    ::IFE::BYTE* __entry = __base + __offset + {vt}::header_size;",
                "    for (std::uint32_t __i = 0; __i < __info.count;",
                f"         ++__i, __entry += {vt}::entry_size) {{",
                f"        const {_entry_struct(block.entry_name or name + '_ENTRY')}&"
                " __e = __info.entries[__i];",
            ]
            for field in block.entry_fields:
                if field.kind == "constant":
                    continue
                out.append(
                    "        "
                    + _write_expression(
                        field, f"{name}::entry", f"__e.{field.name}", types, "__entry"
                    )
                )
            out.append("    }")
        elif _is_blob(block, layout):
            out += [
                "",
                "    if (__info.bytes != nullptr && __info.count != 0)",
                f"        std::memcpy(__base + __offset + {vt}::header_size,",
                "                    __info.bytes, __info.count);",
            ]

        out += [
            "",
            "    // Structural validation is unconditional and inline: a few integer",
            "    // compares over what was just written. __size is the block's own end,",
            "    // which is all validate() looks at.",
            f"    const {name} __written{{__base, __offset,",
            "                            __offset + size_of(__info), VERSION_WRITTEN};",
            "    if (const Status __status = __written.validate(); !__status) return __status;",
            "",
            "    // Spec conformance, only when a layer is attached.",
            f"    if (__hooks != nullptr && __hooks->{name} != nullptr)",
            f"        return __hooks->{name}(__info, __offset, __hooks);",
            "    return {};",
            "}",
        ]


def emit_blocks_header(
    layout: LayoutResult, types: dict[str, Any], header: dict[str, Any]
) -> str:
    """IFE_Blocks.hpp — declarations only, readable as an outline of the format."""
    out: list[str] = [
        _banner(header),
        "#ifndef IFE_Blocks_hpp",
        "#define IFE_Blocks_hpp",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <optional>",
        "",
        '#include "IFE_Constants.hpp"',
        '#include "IFE_VTables.hpp"',
        '#include "IFE_Bytes.hpp"',
        "",
        "// Definitions live in IFE_Blocks.cpp, which follows this file section for",
        "// section. Define IFE_HEADER_ONLY before including this header to fold them",
        "// in at the bottom and use the generated layer without linking anything.",
        "",
        "namespace IFE {",
        "namespace blocks {",
        "",
        "// Forward declarations: offset fields return handles to other blocks, and",
        "// the reference graph has cycles no ordering would resolve.",
    ]
    for name in layout.blocks:
        out.append(f"struct {name};")

    out.append("")
    out.extend(_STATUS_PREAMBLE.strip("\n").splitlines())

    out.append("")
    out.append("// ---- primitive block types ----")
    out.append("// The hierarchy the schema declares, as real base classes.")
    _emit_primitive_bases(out, layout, types)

    for name, block in layout.blocks.items():
        primitive = layout.primitives[block.primitive]
        out.append("")
        out.append(f"// ---- {name} ----")
        out.extend(_comment(block.description))
        out.append(f"struct {name} : public primitives::{block.primitive} {{")
        out.append(f'    static constexpr char type[] = "{name}";')
        recovery_enum = _pascal("recovery_codes")
        out.append(f"    static constexpr ::IFE::constants::{recovery_enum} recovery =")
        out.append(f"        ::IFE::constants::{recovery_enum}::{block.recovery_tag};")
        out.append(
            f"    static constexpr ::IFE::Size header_size = ::IFE::vtables::{name}::header_size;"
        )
        out.append("")
        out.append("    constexpr explicit operator bool() const noexcept { return fits(header_size); }")

        if block.entry_fields:
            entry = block.entry_name or f"{name}_ENTRY"
            out.append("")
            out.append(f"    /// One {entry}, addressed by the array's stored stride.")
            out.append(f"    struct {entry} {{")
            out += [
                "        const ::IFE::BYTE* __base    = nullptr;",
                "        ::IFE::Offset      __offset  = 0;",
                "        ::IFE::Size        __size    = 0;   ///< total file size",
                "        std::uint16_t      __stride  = 0;   ///< as written, not as compiled",
                "        std::uint32_t      __version = 0;",
            ]
            marks = _version_boundaries(block.entry_fields)
            for index, member in enumerate(_entry_members(name, block, types)):
                out.append("")
                _declare(out, member, indent="        ")
                if index in marks:
                    out.append(f"        // Version {marks[index]} ends here.")
                    out.append("        // -------------------------------------------------------")
            out.append("    };")
            out.append("")
            out.append("    /// Entry `i`, stepped by the STRIDE the encoder wrote — never by the")
            out.append("    /// size this build was compiled with.")
            out.append(f"    [[nodiscard]] {entry} entry(std::uint32_t __i) const noexcept;")
            out.append("    [[nodiscard]] ::IFE::Offset entries_begin() const noexcept;")
        elif _is_blob(block, layout):
            out.append("")
            out.append("    /// The whole byte run. Its interpretation is not this layer's")
            out.append("    /// business: slicing comes from a sizes array elsewhere and the")
            out.append("    /// character encoding is normative prose.")
            out.append("    [[nodiscard]] ::IFE::ByteSpan bytes() const noexcept;")
            out.append("    [[nodiscard]] ::IFE::Offset entries_begin() const noexcept;")

        own = tuple(f for f in block.header_fields if f not in primitive.fields)
        marks = _version_boundaries(own)
        for index, member in enumerate(_block_members(name, block, layout, types)):
            out.append("")
            _declare(out, member)
            if index in marks:
                out.append(f"    // Version {marks[index]} ends here.")
                out.append("    // ---------------------------------------------------------------")
        out.append("")
        out.append("    /// Convenience: deep validation from a fresh path.")
        out.append("    [[nodiscard]] Status validate_deep() const noexcept;")
        out.append("};")

    out += [
        "",
        "// ---- writers ----",
        "// What a caller supplies, and the two functions that consume it. The",
        "// machine-written fields never appear here: a CreateInfo carries only what",
        "// the generator cannot derive.",
        "",
        "/// The version a writer stamps and validates against: what this build knows.",
        "inline constexpr std::uint32_t VERSION_WRITTEN =",
        "    (::IFE::IFE_SCHEMA_VERSION_MAJOR << 16) | ::IFE::IFE_SCHEMA_VERSION_MINOR;",
    ]
    _emit_create_infos(out, layout, types)
    _emit_validation_hooks(out, layout)
    _emit_writer_decls(out, layout)

    out += [
        "",
        "}  // namespace blocks",
        "}  // namespace IFE",
        "",
        "#ifdef IFE_HEADER_ONLY",
        "// Header-only mode: fold the definitions in. The include is a no-op on the",
        "// way back through this file's guard, so the recursion terminates.",
        '#include "IFE_Blocks.cpp"',
        "#endif",
        "",
        "#endif  // IFE_Blocks_hpp",
        "",
    ]
    return "\n".join(out)


def emit_blocks_source(
    layout: LayoutResult, types: dict[str, Any], header: dict[str, Any]
) -> str:
    """IFE_Blocks.cpp — definitions, in the header's order, section for section."""
    out: list[str] = [
        _banner(header),
        "#ifndef IFE_Blocks_cpp",
        "#define IFE_Blocks_cpp",
        "",
        "// Compiled as its own translation unit by default; included from",
        "// IFE_Blocks.hpp when IFE_HEADER_ONLY is defined, in which case every",
        "// definition needs internal-or-inline linkage so more than one TU may",
        "// include it. IFE_BLOCKS_INLINE is what makes both work.",
        '#include "IFE_Blocks.hpp"',
        "",
        "#include <cstring>  // byte-array writers copy the payload wholesale",
        "",
        "#ifdef IFE_HEADER_ONLY",
        "#  define IFE_BLOCKS_INLINE inline",
        "#else",
        "#  define IFE_BLOCKS_INLINE",
        "#endif",
        "",
        "namespace IFE {",
        "namespace blocks {",
    ]

    for primitive in layout.primitives.values():
        inherited = layout.primitives[primitive.extends].fields if primitive.extends else ()
        introduced = tuple(f for f in primitive.fields if f not in inherited)
        members = _field_members(introduced, primitive.name, types)
        if not members:
            continue
        out.append("")
        out.append(f"// ---- {primitive.name} (primitive) ----")
        for member in members:
            out.append("")
            out.append(
                f"IFE_BLOCKS_INLINE {member.ret} primitives::{primitive.name}::{member.name}"
                f"({member.params}) {member.quals} {{"
            )
            out.extend(member.body)
            out.append("}")

    for name, block in layout.blocks.items():
        out.append("")
        out.append(f"// ---- {name} ----")

        if block.entry_fields:
            entry = block.entry_name or f"{name}_ENTRY"
            for member in _entry_members(name, block, types):
                out.append("")
                out.append(
                    f"IFE_BLOCKS_INLINE {member.ret} {name}::{entry}::{member.name}"
                    f"({member.params}) {member.quals} {{"
                )
                out.extend(member.body)
                out.append("}")
            out.append("")
            out.append(f"IFE_BLOCKS_INLINE ::IFE::Offset {name}::entries_begin() const noexcept {{")
            out.append("    return entries_at(header_size);")
            out.append("}")
            out.append("")
            out.append(
                f"IFE_BLOCKS_INLINE {name}::{entry} {name}::entry(std::uint32_t __i) const noexcept {{"
            )
            out.append(f"    return {entry}{{__base,")
            out.append("                 entries_begin() + static_cast<::IFE::Offset>(__i) * stride(),")
            out.append("                 __size, stride(), __version};")
            out.append("}")
        elif _is_blob(block, layout):
            out.append("")
            out.append(f"IFE_BLOCKS_INLINE ::IFE::Offset {name}::entries_begin() const noexcept {{")
            out.append("    return entries_at(header_size);")
            out.append("}")
            out.append("")
            out.append(f"IFE_BLOCKS_INLINE ::IFE::ByteSpan {name}::bytes() const noexcept {{")
            out.append("    return {__base + entries_begin(), count()};")
            out.append("}")

        for member in _block_members(name, block, layout, types):
            out.append("")
            out.append(
                f"IFE_BLOCKS_INLINE {member.ret} {name}::{member.name}"
                f"({member.params}) {member.quals} {{"
            )
            out.extend(member.body)
            out.append("}")

        out.append("")
        out.append(f"IFE_BLOCKS_INLINE Status {name}::validate_deep() const noexcept {{")
        out.append("    VisitPath __path;")
        out.append("    return validate_deep(__path);")
        out.append("}")

    out.append("")
    out.append("// ================= writers =================")
    _emit_writer_defs(out, layout, types)

    out += [
        "",
        "}  // namespace blocks",
        "}  // namespace IFE",
        "",
        "#endif  // IFE_Blocks_cpp",
        "",
    ]
    return "\n".join(out)


# ---------------------------------------------------------------------------
# Validation layer. The optional, runtime-attachable spec-conformance
# checks, emitted from the normative clauses in the schema so a diagnostic and
# the published document cite the same source.
# ---------------------------------------------------------------------------


def _clauses(fields: tuple[FieldLayout, ...]) -> list[FieldLayout]:
    return [f for f in fields if f.conformance]


def _requirement(block: str, field: FieldLayout) -> str:
    """The sentence a violation prints, in v1's style: name the clause, then
    cite the section that states it."""
    c = field.conformance or {}
    # The stable clause id, not a section number. A number is positional: a
    # renumbering that lands on another real section makes the diagnostic point
    # confidently at the wrong requirement, and nothing detects it. The id is
    # what the specification anchors, and --validate proves it resolves.
    text = (
        f"{block}.{field.name} {c.get('level', 'shall')} "
        f"{c.get('requirement', 'satisfy the specification')}. "
        f"Per the IFE specification, clause {c.get('clause', '?')}."
    )
    return text.replace('"', "'")


def _check_lines(block: str, field: FieldLayout, value: str, types: dict[str, Any]) -> list[str]:
    """One clause, as C++. Every branch here is a closed-vocabulary predicate;
    there is deliberately no expression syntax to evaluate."""
    c = field.conformance or {}
    message = _requirement(block, field)
    fail = [
        f'        __report(__hooks, "{message}");',
        f'        return {{Check::CONFORMANCE, "{block}", "{field.name}",',
        f"                static_cast<std::uint64_t>({value}), 0, __at}};",
    ]
    out: list[str] = []
    if "minimum" in c:
        out += [f"    if ({value} < {c['minimum']}) {{"] + fail + ["    }"]
    if "maximum" in c:
        out += [f"    if ({value} > {c['maximum']}) {{"] + fail + ["    }"]
    if c.get("non_null"):
        out += [f"    if ({value} == ::IFE::constants::NULL_OFFSET) {{"] + fail + ["    }"]
    if c.get("enum_member"):
        enum = _pascal(field.type_name)
        out += [f"    if (!is_member(static_cast<::IFE::constants::{enum}>({value}))) {{"] + fail + ["    }"]
    return out


def emit_validation_source(
    layout: LayoutResult, constants_doc: dict[str, Any], types: dict[str, Any],
    header: dict[str, Any]
) -> str:
    """IFE_Validation.cpp — the conformance layer behind the writers' hook."""
    out: list[str] = [
        _banner(header),
        "// The optional layer: attachable at runtime,",
        "// costing a null check when absent, and free to be verbose because it",
        "// never runs in a shipped product's hot path. Every check below is",
        "// generated from a normative clause in spec/ife_fields.json, so a",
        "// diagnostic and the published specification cite one source.",
        "",
        '#include "IFE_Validation.hpp"',
        "",
        "namespace IFE {",
        "namespace blocks {",
        "namespace {",
        "",
        "void __report(const ValidationHooks* __hooks, const char* __message) noexcept {",
        "    // The layer formats; the caller decides what I/O means. Silent when",
        "    // no messenger was registered -- the Status still carries the failure.",
        "    if (__hooks != nullptr && __hooks->diagnostic != nullptr)",
        "        __hooks->diagnostic(__message, __hooks->user);",
        "}",
    ]

    # Membership predicates, one per enum group the clauses reference.
    referenced: dict[str, None] = {}
    for name, block in layout.blocks.items():
        for field in _clauses(block.header_fields) + _clauses(block.entry_fields):
            if (field.conformance or {}).get("enum_member"):
                referenced[field.type_name] = None
    for group_name in referenced:
        group = constants_doc.get(group_name, {})
        members = [
            member
            for entries in group.get("ife_version", {}).values()
            for member in entries
        ]
        enum = _pascal(group_name)
        out += [
            "",
            f"/// Whether a value names a declared member of {group_name}.",
            f"[[nodiscard]] bool is_member(::IFE::constants::{enum} __v) noexcept {{",
            "    switch (__v) {",
        ]
        out += [f"        case ::IFE::constants::{enum}::{m}:" for m in members]
        out += ["            return true;", "    }", "    return false;", "}"]

    out += ["", "}  // namespace"]

    # One check per block carrying clauses.
    checked: list[str] = []
    for name, block in layout.blocks.items():
        header_clauses = _clauses(block.header_fields)
        entry_clauses = _clauses(block.entry_fields)
        if not header_clauses and not entry_clauses:
            continue
        checked.append(name)
        info = _create_info(name)
        out += [
            "",
            f"// ---- {name} ----",
            f"Status check_{name}(const {info}& __info, ::IFE::Offset __at,",
            "                    const ValidationHooks* __hooks) noexcept {",
        ]
        for field in header_clauses:
            out += _check_lines(name, field, f"__info.{field.name}", types)

        if entry_clauses:
            entry = _entry_struct(block.entry_name or f"{name}_ENTRY")
            out += [
                "",
                "    for (std::uint32_t __i = 0; __i < __info.count; ++__i) {",
                f"        const {entry}& __e = __info.entries[__i];",
            ]
            for field in entry_clauses:
                if (field.conformance or {}).get("ordering"):
                    continue
                out += ["    " + line for line in
                        _check_lines(f"{name}.{block.entry_name}", field, f"__e.{field.name}", types)]
            out.append("    }")

            # Ordering is the one clause that is about the sequence rather than
            # a value, so it gets its own pass over the entries.
            for field in entry_clauses:
                order = (field.conformance or {}).get("ordering")
                if not order:
                    continue
                message = _requirement(f"{name}.{block.entry_name}", field)
                out += [
                    "",
                    f"    for (std::uint32_t __i = 1; __i < __info.count; ++__i) {{",
                    f"        if (!(__info.entries[__i].{field.name} >"
                    f" __info.entries[__i - 1].{field.name})) {{",
                    f'            __report(__hooks, "{message}");',
                    f'            return {{Check::CONFORMANCE, "{name}", "{field.name}",',
                    f"                    static_cast<std::uint64_t>(__i), 0, __at}};",
                    "        }",
                    "    }",
                ]

        out += [
            "",
            "    // Layers chain, as Vulkan's do: this one passed, so ask the next.",
            f"    if (__hooks != nullptr && __hooks->next != nullptr && __hooks->next->{name} != nullptr)",
            f"        return __hooks->next->{name}(__info, __at, __hooks->next);",
            "    return {};",
            "}",
        ]

    out += [
        "",
        "const ValidationHooks& conformance_layer() noexcept {",
        "    static const ValidationHooks __layer = [] {",
        "        ValidationHooks __h{};",
    ]
    out += [f"        __h.{name} = &check_{name};" for name in checked]
    out += [
        "        return __h;",
        "    }();",
        "    return __layer;",
        "}",
        "",
        "}  // namespace blocks",
        "}  // namespace IFE",
        "",
    ]
    return "\n".join(out)


def emit_validation_header(layout: LayoutResult, header: dict[str, Any]) -> str:
    """IFE_Validation.hpp — how an application attaches the layer."""
    return "\n".join([
        _banner(header),
        "#ifndef IFE_Validation_hpp",
        "#define IFE_Validation_hpp",
        "",
        '#include "IFE_Blocks.hpp"',
        "",
        "namespace IFE {",
        "namespace blocks {",
        "",
        "/// The spec-conformance layer.",
        "///",
        "/// Attach it once, at writer creation, by passing it to store():",
        "///",
        "///     ValidationHooks hooks = conformance_layer();",
        "///     hooks.diagnostic = [](const char* m, void*) { std::fputs(m, stderr); };",
        "///     store(base, offset, info, &hooks);",
        "///",
        "/// Detached -- the default -- a store costs one null check and the",
        "/// structural validate(). Attached, every `shall` clause in the schema is",
        "/// enforced and each diagnostic cites the section that states it.",
        "///",
        "/// A development tool, not a production dependency: it lives in its own",
        "/// library (IrisFileExtensionValidation) so an application links it only",
        "/// when it wants it, exactly as a Vulkan validation layer is.",
        "///",
        "/// Copy the returned struct before setting `diagnostic` or `next` -- the",
        "/// layer itself is shared and immutable.",
        "[[nodiscard]] const ValidationHooks& conformance_layer() noexcept;",
        "",
        "}  // namespace blocks",
        "}  // namespace IFE",
        "",
        "#endif  // IFE_Validation_hpp",
        "",
    ])
