_RESERVED_ACCESSORS = frozenset({"type", "recovery", "header_size", "entry_size", "size"})


class Member(NamedTuple):
    """One member function, rendered as a declaration and as a definition.

    Splitting the signature into parts is what lets the source qualify it
    (`Status FILE_HEADER::validate() const noexcept`) from the same record the
    header prints unqualified. Nothing may render one without the other.
    """

    doc: tuple[str, ...]        # /// lines, declaration only
    attrs: str                  # [[nodiscard]] and the like, declaration only
    ret: str
    name: str
    params: str
    quals: str                  # "const noexcept"
    body: tuple[str, ...]       # definition lines, without the braces


def _declare(out: list[str], member: Member, indent: str = "    ") -> None:
    out.extend(f"{indent}{line}" for line in member.doc)
    attrs = f"{member.attrs} " if member.attrs else ""
    out.append(f"{indent}{attrs}{member.ret} {member.name}({member.params}) {member.quals};")


def _define(out: list[str], owner: str, member: Member) -> None:
    out.append("")
    out.append(f"{member.ret} {owner}::{member.name}({member.params}) {member.quals} {{")
    out.extend(member.body)
    out.append("}")


def _accessor(field_name: str) -> str:
    """Accessor name for a field: the field name, lower-cased.

    RECOVERY would collide with the static `recovery` tag constant, so names
    clashing with a struct-scope member take a `_field` suffix. Mechanical, so
    the name is predictable from the spec.
    """
    name = field_name.lower()
    return f"{name}_field" if name in _RESERVED_ACCESSORS else name


def _version_of(since: str) -> int:
    major, minor = version_key(since)
    return (major << 16) | minor


def _read_expression(field: FieldLayout, types: dict[str, Any]) -> tuple[str, str]:
    """(return type, expression) for reading one field through IFE_Bytes.

    `offset::` and `size::` are unqualified: every body this feeds is a
    member function of the block (or its entry type), whose nested `offset`/
    `size` tables the fold put there.
    """
    at = f"__base + __offset + offset::{field.name}"
    if field.kind == "enum":
        enum = f"::IFE::constants::{_pascal(field.type_name)}"
        underlying = _cpp_of(field.type_name, types) if field.type_name in types else field.cpp_type
        return enum, f"static_cast<{enum}>(::IFE::load<{underlying}>({at}))"
    canonical = _canonical_type(field.type_name, types)
    if canonical == "u24":
        return "std::uint32_t", f"::IFE::load_u24({at})"
    if canonical == "u40":
        return "std::uint64_t", f"::IFE::load_u40({at})"
    if canonical == "f16":
        return "float", f"::IFE::load_f16({at})"
    return field.cpp_type, f"::IFE::load<{field.cpp_type}>({at})"


def _field_members(
    fields: tuple[FieldLayout, ...],
    types: dict[str, Any],
    stride_gated: bool = False,
) -> list[Member]:
    """One Member per readable field, in wire order."""
    members: list[Member] = []
    for field in fields:
        if field.kind == "constant":
            continue  # always holds its sentinel; validated, never read
        doc = tuple(f"/// {line}" for line in field.description.splitlines() if line.strip())

        if field.points_to:
            target = field.points_to
            note = (
                "Empty when the offset is NULL_OFFSET."
                if field.nullable
                else "Required: never NULL_OFFSET in a valid file."
            )
            body = []
            if field.since != "1.0":
                # An appended offset needs the same version gate as any other
                # appended field. It reads as absent rather than as an empty
                # optional because that is what an offset field's absence
                # already looks like -- a falsy handle, exactly as NULL_OFFSET
                # produces. Without this the accessor loads eight bytes past
                # the end of the block a file of an earlier version wrote, and
                # follows whatever it finds there.
                body.append(f"    if (__version < {_version_of(field.since):#010x}u) return {target}{{}};")
            body += [
                f"    const ::IFE::Offset __at = ::IFE::load<::IFE::Offset>(",
                f"        __base + __offset + offset::{field.name});",
            ]
            if field.nullable:
                body.append(f"    if (__at == ::IFE::constants::NULL_OFFSET) return {target}{{}};")
            body.append(f"    return {target}{{__base, __at, __size, __version}};")
            since_note = (f" Empty in a file written before {field.since}."
                          if field.since != "1.0" else "")
            members.append(Member(
                doc=doc + (f"/// Handle to the {target} block this offset references. {note}{since_note}",),
                attrs="[[nodiscard]]", ret=target, name=_accessor(field.name),
                params="", quals="const noexcept", body=tuple(body),
            ))
            continue

        cpp, expression = _read_expression(field, types)
        if field.since != "1.0":
            guard = f"__version < {_version_of(field.since):#010x}u"
            if stride_gated:
                guard += (
                    f"\n        || __stride < offset::{field.name}"
                    f" + size::{field.name}"
                )
            members.append(Member(
                doc=doc + (f"/// Added in {field.since}; empty when the file predates it.",),
                attrs="[[nodiscard]]", ret=f"std::optional<{cpp}>", name=_accessor(field.name),
                params="", quals="const noexcept",
                body=(f"    if ({guard}) return std::nullopt;", f"    return {expression};"),
            ))
        else:
            members.append(Member(
                doc=doc, attrs="[[nodiscard]]", ret=cpp, name=_accessor(field.name),
                params="", quals="const noexcept", body=(f"    return {expression};",),
            ))
    return members


def _version_boundaries(fields: tuple[FieldLayout, ...]) -> dict[int, str]:
    """Index -> version whose last readable field sits there."""
    marks: dict[int, str] = {}
    readable = [f for f in fields if f.kind != "constant"]
    for i, field in enumerate(readable):
        if i + 1 == len(readable) or readable[i + 1].since != field.since:
            marks[i] = field.since
    return marks


def _validate_member(name: str, block: Any, layout: LayoutResult) -> Member:
    """The block's own structural checks, in the order v1 performs them.

    Reproduces DATA_BLOCK::validate_offset in the retired hand-written layer, and
    the array bounds check from LAYER_EXTENTS::validate_full (:1641-1686).
    Deliberately absent is anything semantic: FILE_SIZE agreeing with the size
    the OS reports is a fact about the file, not the layout, and belongs to the
    runtime.
    """
    primitive = layout.primitives[block.primitive]
    body: list[str] = [
        "    if (!*this)",
        '        return {Check::NOT_CONSTRUCTED, type, "", __offset, __size, __offset};',
    ]
    by_name = {f.name: f for f in primitive.fields}
    if "VALIDATION" in by_name:
        body += [
            "    // A block stores its own offset, so a pointer that landed here can",
            "    // prove it landed where it meant to.",
        ]
        at = by_name["VALIDATION"].offset
        # VALIDATION stores its own position. For a forward block that is the
        # block's start, which is what the handle's offset already is; for a
        # trailer the field sits at a fixed displacement behind the anchor, and
        # the block's start is not a stable thing to store because appending
        # moves it.
        own = "__offset" if at == 0 else f"__offset + offset::VALIDATION"
        if by_name["VALIDATION"].since != "1.0":
            # The whole block postdates 1.0, so its own VALIDATION is version
            # gated like any appended field. A file that predates the block
            # cannot contain one: the gated accessor is empty, and there is
            # nothing to compare against bytes that mean something else. Skip
            # rather than reject — a newer file is never a structural failure.
            body += [
                "    // VALIDATION postdates this reader's version; the accessor is",
                "    // gated empty, so there is nothing to check it against. Skip:",
                "    // a newer file is never a structural failure.",
                f"    if (const auto __vo = validation(); __vo && *__vo != {own})",
                f'        return {{Check::BAD_VALIDATION, type, "VALIDATION", *__vo, {own}, __offset}};',
            ]
        else:
            body += [
                f"    if (const ::IFE::Offset __v = validation(); __v != {own})",
                f'        return {{Check::BAD_VALIDATION, type, "VALIDATION", __v, {own}, __offset}};',
            ]
    for field in primitive.fields:
        if field.kind == "constant":
            body += [
                f"    if (const auto __c = ::IFE::load<{field.cpp_type}>(",
                f"            __base + __offset + offset::{field.name});",
                f"        __c != ::IFE::constants::{field.constant})",
                f'        return {{Check::BAD_CONSTANT, type, "{field.name}", __c,',
                f"                ::IFE::constants::{field.constant}, __offset}};",
            ]
    # An untagged block has no RECOVERY field to check against -- what
    # identifies it is the shape of its VALIDATION, checked above.
    if "RECOVERY" in by_name and block.recovery_tag:
        body += [
            "    if (const auto __r = recovery_field(); __r != recovery)",
            '        return {Check::BAD_RECOVERY, type, "RECOVERY",',
            "                static_cast<std::uint64_t>(__r),",
            "                static_cast<std::uint64_t>(recovery), __offset};",
        ]
    if _has_count(block, layout):
        if block.entry_fields:
            floor = block.entry_sizes[0][1] if block.entry_sizes else block.entry_size
            body += [
                "",
                "    // The stride the encoder wrote must at least hold the entry this",
                "    // build knows; a wider one is a later version and is fine.",
                f"    if (const std::uint16_t __st = stride(); __st < {floor})",
                f'        return {{Check::BAD_STRIDE, type, "STRIDE", __st, {floor}, __offset}};',
            ]
            span = "static_cast<std::uint64_t>(stride()) * count()"
        else:
            body += ["", "    // A byte array stores no stride; its stride is one by definition."]
            span = "static_cast<std::uint64_t>(count())"
        body += [
            "",
            "    // Expressed as a subtraction so the multiplication cannot wrap:",
            "    // u16 * u32 fits a u64 comfortably.",
            "    const ::IFE::Offset __begin = entries_begin();",
            f"    const std::uint64_t __span = {span};",
            "    if (__begin > __size || __span > __size - __begin)",
            '        return {Check::ARRAY_OVERRUN, type, "COUNT", __span,',
            "                __size - (__begin > __size ? __size : __begin), __offset};",
        ]
    body.append("    return {};")
    return Member(
        doc=("/// Structural checks on this block alone. Never allocates or throws.",),
        attrs="[[nodiscard]]", ret="Status", name="validate", params="",
        quals="const noexcept", body=tuple(body),
    )


def _validate_deep_member(name: str, block: Any) -> Member:
    """Recurse the offset graph. Successor to v1's hand-threaded validate_full.

    v1 chained each block's check into its children by hand (:869-900), which
    is why a block added later is easy to forget. Here the walk is derived from
    `points_to`, so every edge in the schema is followed by construction —
    including edges leaving array *entries*, which a header-only walk would
    skip and which is exactly where IMAGE_BYTES and ANNOTATION_BYTES hang.
    """
    body: list[str] = [
        "    if (const Status __s = validate(); !__s) return __s;",
        "    if (__path.contains(__offset))",
        '        return {Check::CYCLE, type, "", __offset, 0, __offset};',
        "    if (!__path.push(__offset))",
        '        return {Check::CYCLE, type, "", __path.depth, MAX_BLOCK_DEPTH, __offset};',
    ]

    def walk(field, source: str, indent: str) -> list[str]:
        handle = f"__t_{field.name.lower()}"
        lines = [f"{indent}{{", f"{indent}    const auto {handle} = {source};"]
        if field.nullable:
            lines += [
                f"{indent}    // Optional: NULL_OFFSET means absent and is legal; any",
                f"{indent}    // other unusable value is not.",
                f"{indent}    if ({handle}.__offset != ::IFE::constants::NULL_OFFSET) {{",
            ]
        else:
            lines.append(f"{indent}    {{")
        inner = indent + "        "
        lines += [
            f"{inner}if (!{handle})",
            f'{inner}    return {{Check::OUT_OF_BOUNDS, type, "{field.name}",',
            f"{inner}            {handle}.__offset, __size, __offset}};",
            f"{inner}if (const Status __s = {handle}.validate_deep(__path); !__s) return __s;",
            f"{indent}    }}",
            f"{indent}}}",
        ]
        return lines

    for field in (f for f in block.header_fields if f.points_to):
        body += walk(field, f"{_accessor(field.name)}()", "    ")
    entry_edges = [f for f in block.entry_fields if f.points_to]
    if entry_edges:
        body += ["", "    // Edges that leave from entries, one per entry.",
                 "    for (std::uint32_t __i = 0; __i < count(); ++__i) {",
                 "        const auto __e = entry(__i);"]
        for field in entry_edges:
            body += walk(field, f"__e.{_accessor(field.name)}()", "        ")
        body.append("    }")
    body += ["    __path.pop();", "    return {};"]
    return Member(
        doc=("/// validate(), then every block this one reaches, transitively.",),
        attrs="[[nodiscard]]", ret="Status", name="validate_deep",
        params="VisitPath& __path", quals="const noexcept", body=tuple(body),
    )


_STATUS_PREAMBLE = """
// ---- validation vocabulary ----
// Generated validators never allocate, never throw and never format a string.
// They report a code plus the operands the retired hand-written layer
// interpolated into its messages, and leave the wording to the runtime, which
// has the JSON descriptions and is not on the hot path.

enum class Check : std::uint8_t {
    OK = 0,
    NOT_CONSTRUCTED,   ///< no base pointer, null offset, or header past EOF
    OUT_OF_BOUNDS,     ///< an offset field points outside the file
    BAD_VALIDATION,    ///< VALIDATION does not equal the block's own offset
    BAD_RECOVERY,      ///< RECOVERY is not this block's tag
    BAD_CONSTANT,      ///< a constant field does not hold its sentinel
    BAD_STRIDE,        ///< STRIDE is zero, or narrower than the entry it must hold
    ARRAY_OVERRUN,     ///< the entry run extends past the end of the file
    CYCLE,             ///< an offset chain returns to a block already on the path
    TOO_DEEP,          ///< a chain is longer than a reader will follow, without repeating
    BAD_NESTED_VALUE,  ///< a nested attribute value is not a whole number of offsets
    CONFORMANCE,       ///< a normative clause was violated; only the conformance layer raises this
};

/// Everything needed to describe a failure, unformatted.
struct Status {
    Check         code     = Check::OK;
    const char*   block    = "";
    const char*   field    = "";
    std::uint64_t found    = 0;
    std::uint64_t expected = 0;
    ::IFE::Offset at       = 0;

    constexpr explicit operator bool() const noexcept { return code == Check::OK; }
};

/// A newer file is never a structural failure: append-only guarantees its 1.0
/// prefix is readable, so generated validators have no newer-version code at
/// all. Where a field postdates the reader's version it is gated empty by the
/// accessor and is simply not checked.

inline constexpr std::size_t MAX_BLOCK_DEPTH = 16;

/// The chain of offsets from the root to the block being checked.
///
/// Cycle detection needs the *ancestry*, not every block ever seen: a file may
/// hold thousands of annotations each with its own byte array, all legitimate
/// separate visits, and a global set would reject the second of two entries
/// pointing at one target. A cycle is an offset that reappears on the current
/// path, bounded by the block graph's depth.
struct VisitPath {
    ::IFE::Offset entries[MAX_BLOCK_DEPTH]{};
    std::size_t   depth = 0;

    [[nodiscard]] constexpr bool contains(::IFE::Offset __o) const noexcept {
        for (std::size_t __i = 0; __i < depth; ++__i)
            if (entries[__i] == __o) return true;
        return false;
    }
    [[nodiscard]] constexpr bool push(::IFE::Offset __o) noexcept {
        if (depth == MAX_BLOCK_DEPTH) return false;
        entries[depth++] = __o;
        return true;
    }
    constexpr void pop() noexcept { if (depth) --depth; }
};
"""


def _block_members(
    name: str, block: Any, layout: LayoutResult, types: dict[str, Any]
) -> list[Member]:
    """Every member of one block struct, declaration order == definition order."""
    primitive = layout.primitives[block.primitive]
    own = tuple(f for f in block.header_fields if f not in primitive.fields)
    members = _field_members(own, types)
    members.append(_validate_member(name, block, layout))
    members.append(_validate_deep_member(name, block))
    return members


def _entry_members(name: str, block: Any, types: dict[str, Any]) -> list[Member]:
    return _field_members(block.entry_fields, types, stride_gated=True)


def _primitive_chain(block: Any, layout: LayoutResult) -> list[Any]:
    """The block's primitive ancestry, root first."""
    chain: list[Any] = []
    prim = layout.primitives[block.primitive]
    while prim is not None:
        chain.append(prim)
        prim = layout.primitives[prim.extends] if prim.extends else None
    chain.reverse()
    return chain


def _emit_folded_primitive(
    out: list[str], block: Any, layout: LayoutResult, types: dict[str, Any]
) -> None:
    """The machine-written prefix: state and shared accessors, inline.

    The retired layer kept these in one struct per block; the generated layer
    factored them into primitives base classes to single-source the shared
    accessors. A generated header may duplicate freely — the JSON is the
    source of truth, not the C++ — so the fold brings the members back into
    each block and the `primitives::` indirection disappears from view.
    """
    chain = _primitive_chain(block, layout)
    out += [
        "    const ::IFE::BYTE* __base    = nullptr;",
        "    ::IFE::Offset      __offset  = ::IFE::constants::NULL_OFFSET;",
        "    ::IFE::Size        __size    = 0;   ///< total file size",
        "    std::uint32_t      __version = 0;   ///< major<<16 | minor, from FILE_HEADER",
        "",
        "    /// Whether a block of `__header_size` bytes fits here. Stricter than",
        "    /// the retired hand-written layer's operator bool, which checked only",
        "    /// that the offset is in range: requiring the whole header to fit",
        "    /// makes a truncated file fail at construction rather than mid-read.",
    ]
    if chain[0].backward:
        out += [
            "    ///",
            "    /// This block lays its fields out *before* `__offset`, so the",
            "    /// test is that the header fits behind it rather than ahead of it.",
            "    /// Getting that backwards underflows past the start of the file.",
            "    [[nodiscard]] constexpr bool fits(::IFE::Size __header_size) const noexcept {",
            "        return __base != nullptr",
            "            && __offset != ::IFE::constants::NULL_OFFSET",
            "            && __offset >= __header_size",
            "            && __offset <= __size;",
            "    }",
        ]
    else:
        out += [
            "    [[nodiscard]] constexpr bool fits(::IFE::Size __header_size) const noexcept {",
            "        return __base != nullptr",
            "            && __offset != ::IFE::constants::NULL_OFFSET",
            "            && __offset + __header_size <= __size;",
            "    }",
        ]
    for prim in chain:
        inherited = layout.primitives[prim.extends].fields if prim.extends else ()
        introduced = tuple(f for f in prim.fields if f not in inherited)
        for member in _field_members(introduced, types):
            out.append("")
            _declare(out, member)
    # Whichever primitives carry a COUNT are the ones with something after
    # the header to address. Keyed on the field rather than on the
    # primitive's name, which the schema is free to change.
    if any(f.name == "COUNT" for prim in chain for f in prim.fields):
        out += [
            "",
            "    /// Where the entry run starts. Takes the derived block's header size",
            "    /// for the same reason `fits` does.",
            "    [[nodiscard]] constexpr ::IFE::Offset entries_at(",
            "            ::IFE::Size __header_size) const noexcept {",
            "        return __offset + __header_size;",
            "    }",
        ]


# ---------------------------------------------------------------------------
# Writers. Per block: a CreateInfo carrying what only the caller knows,
# a size_of, and a store. Replaces v1's 22 hand-written free functions -- 9
# SIZE_* and 13 STORE_* -- none of which survive.
# ---------------------------------------------------------------------------

# The primitive fields are the machine-written prefix: a caller never supplies
# one, because store() derives each from something it already has. Keyed by
# name deliberately -- the primitive vocabulary is closed (four primitives,
# five distinct fields) and declared in the schema, so an unrecognised one
# means the schema grew a concept the writer does not know how to fill. That
# raises rather than emitting a store() that silently leaves bytes unwritten.
_PRIMITIVE_FIELDS = frozenset({"MAGIC", "VALIDATION", "RECOVERY", "STRIDE", "COUNT"})


def _create_info(block_name: str) -> str:
    return f"{_pascal(block_name)}CreateInfo"


def _entry_struct(entry_name: str) -> str:
    """LAYER_EXTENT -> LayerExtentEntry, IMAGE_ENTRY -> ImageEntry."""
    stem = entry_name[: -len("_ENTRY")] if entry_name.endswith("_ENTRY") else entry_name
    return f"{_pascal(stem)}Entry"


def _writer_type(field: FieldLayout, types: dict[str, Any]) -> str:
    """The type a caller supplies for one field -- the mirror of _read_expression."""
    if field.kind == "enum":
        return f"::IFE::constants::{_pascal(field.type_name)}"
    canonical = _canonical_type(field.type_name, types)
    if canonical == "u24":
        return "std::uint32_t"
    if canonical == "u40":
        return "std::uint64_t"
    if canonical == "f16":
        return "float"
    return field.cpp_type


def _writer_default(field: FieldLayout) -> str:
    """Offsets default to NULL_OFFSET, everything else to a value-initialised zero.

    Every points_to member gets NULL_OFFSET, not only the nullable ones: zero
    is a legal offset (it is the file header), so an offset left unset would
    otherwise point somewhere plausible instead of somewhere obviously wrong.

    FILE_HEADER's EXTENSION_MAJOR/MINOR default to the schema version this
    build writes. The generated store() always lays out the newest fields,
    so a file must claim the version its bytes actually have; defaulting the
    only two fields that say what version a file is makes the self-consistent
    choice the zero-effort one. A writer that needs an older claim sets them
    explicitly -- which is exactly the moment to think about the layout that
    claim implies.
    """
    if field.points_to:
        return "::IFE::constants::NULL_OFFSET"
    if field.name == "EXTENSION_MAJOR":
        return "::IFE::IFE_SCHEMA_VERSION_MAJOR"
    if field.name == "EXTENSION_MINOR":
        return "::IFE::IFE_SCHEMA_VERSION_MINOR"
    return "{}"


def _write_expression(
    field: FieldLayout, vtable: str, value: str, types: dict[str, Any], base: str
) -> str:
    """One store through IFE_Bytes. The exact inverse of _read_expression."""
    at = f"{base} + ::IFE::blocks::{vtable}::offset::{field.name}"
    if field.kind == "enum":
        underlying = _cpp_of(field.type_name, types) if field.type_name in types else field.cpp_type
        return f"::IFE::store<{underlying}>({at}, static_cast<{underlying}>({value}));"
    canonical = _canonical_type(field.type_name, types)
    if canonical == "u24":
        return f"::IFE::store_u24({at}, {value});"
    if canonical == "u40":
        return f"::IFE::store_u40({at}, {value});"
    if canonical == "f16":
        return f"::IFE::store_f16({at}, {value});"
    return f"::IFE::store<{field.cpp_type}>({at}, {value});"


def _caller_fields(block: Any, layout: LayoutResult) -> tuple[FieldLayout, ...]:
    """The header fields a CreateInfo carries: this block's own, minus constants."""
    primitive = layout.primitives[block.primitive]
    own = tuple(f for f in block.header_fields if f not in primitive.fields)
    return tuple(f for f in own if f.kind != "constant")


def _pairs_entry_struct(layout: LayoutResult) -> str:
    """The C++ name of the payload the `from_pairs` blocks share.

    Taken from whichever of them declares the entry, because that is what
    `from_pairs` means: several blocks, one semantic payload. Deriving it
    rather than naming a block keeps the pairing in the schema, where it was
    put deliberately.
    """
    for name, block in layout.blocks.items():
        if block.from_pairs and block.entry_fields:
            return _entry_struct(block.entry_name or f"{name}_ENTRY")
    raise SpecError(
        "a block declares from_pairs but none of the from_pairs blocks declares an "
        "entry; the shared payload type has nothing to take its shape from"
    )


def _emit_create_infos(out: list[str], layout: LayoutResult, types: dict[str, Any]) -> None:
    """Entry PODs and CreateInfo structs, in block order."""
    pairs_entry = (
        _pairs_entry_struct(layout)
        if any(b.from_pairs for b in layout.blocks.values())
        else None
    )
    for name, block in layout.blocks.items():
        if block.from_pairs:
            # The attribute blocks share one semantic payload: the attributes
            # themselves. store() derives both the sizes array and the packed
            # byte run from it, so the slicing cannot drift from the bytes it
            # describes (the retired layer took the same semantic payload).
            if block.entry_fields:
                out += [
                    "",
                    "/// One attribute: a key, and a value that is either text or a",
                    "/// sequence of nested attribute structures.",
                    "///",
                    "/// Which of the two it is, is stated by KIND rather than inferred",
                    "/// from `nested` being empty: an empty sequence and an empty string",
                    "/// are both legal values and are not the same thing.",
                    f"struct {pairs_entry} {{",
                    "    /// The attribute key. ASCII, or a four-byte DICOM tag.",
                    "    std::string key;",
                    "    /// The value's bytes, when KIND is ATTRIBUTE_STRING. UTF-8 by",
                    "    /// the specification, uninterpreted here.",
                    "    std::string value;",
                    "    /// File offsets of the nested attributes blocks -- the items of a",
                    "    /// DICOM sequence -- when KIND is ATTRIBUTE_NESTED. Where those",
                    "    /// blocks sit stays the caller's decision, as it is for every",
                    "    /// other offset in this layer.",
                    "    std::vector<::IFE::Offset> nested;",
                    "    /// Which of the two the value is.",
                    "    ::IFE::constants::AttributeKinds KIND =",
                    "        ::IFE::constants::AttributeKinds::ATTRIBUTE_STRING;",
                    "};",
                    "",
                    "/// Wire width of one nested-structure offset: a plain 64-bit absolute",
                    "/// file offset, the same thing every other offset in the format is.",
                    "/// A relative displacement would buy no relocatability, since every",
                    "/// block stores its own absolute offset in VALIDATION regardless, and",
                    "/// a packed width would buy three bytes per item at the cost of being",
                    "/// the one offset in IFE that is not shaped like the others.",
                    "inline constexpr ::IFE::Size NESTED_OFFSET_SIZE = 8;",
                    "",
                    "/// How many bytes of the attribute byte array one value occupies.",
                    "///",
                    "/// VALUE_SIZE does not change meaning with KIND -- it is always the",
                    "/// length of the value's slice -- which is what lets a reader walk the",
                    "/// packed run without interpreting a single value. A string value is",
                    "/// its own length; a nested one is five bytes per item it locates, so",
                    "/// a sequence of no items is a legal value of length zero.",
                    "[[nodiscard]] inline ::IFE::Size attribute_value_bytes(",
                    f"        const {pairs_entry}& __e) noexcept {{",
                    "    return __e.KIND == ::IFE::constants::AttributeKinds::ATTRIBUTE_NESTED",
                    "         ? __e.nested.size() * NESTED_OFFSET_SIZE",
                    "         : __e.value.size();",
                    "}",
                    "",
                    "/// How many nested structures a value slice of `__value_size` bytes",
                    "/// locates. Read a nested value through this and nested_offset() rather",
                    "/// than dividing: the wire stores a length because that is what lets a",
                    "/// decoder walk the packed run without interpreting any value, but a",
                    "/// caller thinks in items and should never see the eight.",
                    "[[nodiscard]] inline ::IFE::Size nested_count(::IFE::Size __value_size) noexcept {",
                    "    return __value_size / NESTED_OFFSET_SIZE;",
                    "}",
                    "",
                    "/// The offset of nested structure `__i` within a value slice.",
                    "[[nodiscard]] inline ::IFE::Offset nested_offset(",
                    "        const ::IFE::BYTE* __value, ::IFE::Size __i) noexcept {",
                    "    return ::IFE::load<std::uint64_t>(__value + __i * NESTED_OFFSET_SIZE);",
                    "}",
                    "",
                    "/// Whether a value slice of `__value_size` bytes is a whole number of",
                    "/// offsets. The one rule about these bytes the schema's capped predicate",
                    "/// vocabulary cannot state, so it is stated in the specification prose",
                    "/// and checked here.",
                    "[[nodiscard]] inline bool nested_size_is_whole(::IFE::Size __value_size) noexcept {",
                    "    return __value_size % NESTED_OFFSET_SIZE == 0;",
                    "}",
                    "",
                    "/// Encode-time check on one attribute payload, run by store() before it",
                    "/// writes anything.",
                    "///",
                    "/// Divisibility cannot fail here -- a nested value's size is derived as",
                    "/// `nested.size() * NESTED_OFFSET_SIZE`, so the writer cannot produce a",
                    "/// partial offset even if asked to. What can fail is the payload",
                    "/// disagreeing with its own KIND, and that is worth catching because the",
                    "/// failure is silent otherwise: a caller who sets ATTRIBUTE_NESTED and",
                    "/// then fills `value` would have their text dropped and a well-formed",
                    "/// empty sequence written in its place.",
                    f"[[nodiscard]] inline bool attribute_payload_agrees(const {pairs_entry}& __e) noexcept {{",
                    "    return __e.KIND == ::IFE::constants::AttributeKinds::ATTRIBUTE_NESTED",
                    "         ? __e.value.empty()",
                    "         : __e.nested.empty();",
                    "}",
                    "",
                    "/// Whether a payload's sizes fit the fields that carry them.",
                    "///",
                    "/// KEY_SIZE is a u16 and VALUE_SIZE a u32, while the byte run is written",
                    "/// from the strings themselves. A key past 65535 bytes would therefore",
                    "/// store a truncated length beside untruncated bytes, and every later",
                    "/// read would slice from the wrong boundary -- a corrupt file the",
                    "/// writer reported success on. Caught here, where the payload is",
                    "/// already in hand, rather than left for a reader to discover.",
                    "[[nodiscard]] inline bool attribute_payload_fits(",
                    f"        const {pairs_entry}& __e) noexcept {{",
                    "    return __e.key.size() <= (std::numeric_limits<std::uint16_t>::max)()",
                    "        && attribute_value_bytes(__e)",
                    "               <= (std::numeric_limits<std::uint32_t>::max)();",
                    "}",
                ]
            out.append("")
            out.extend(_comment(block.description))
            out.append(f"struct {_create_info(name)} {{")
            out += [
                "    /// The attributes. store() derives both the sizes array and the",
                "    /// packed byte run from these -- the slicing cannot drift because",
                "    /// it is derived here, not supplied.",
                f"    const std::vector<{pairs_entry}>& entries;",
            ]
            out.append("};")
            continue

        if block.entry_fields:
            entry = _entry_struct(block.entry_name or f"{name}_ENTRY")
            out.append("")
            out.append(f"/// One entry to write into {name}. Members are the spec's field")
            out.append("/// names verbatim, so a caller reads the specification directly.")
            out.append(f"struct {entry} {{")
            for field in block.entry_fields:
                if field.kind == "constant":
                    continue
                for line in field.description.splitlines():
                    if line.strip():
                        out.append(f"    /// {line}")
                out.append(
                    f"    {_writer_type(field, types)} {field.name} = {_writer_default(field)};"
                )
            out.append("};")

        out.append("")
        out.extend(_comment(block.description))
        out.append(f"struct {_create_info(name)} {{")
        for field in _caller_fields(block, layout):
            for line in field.description.splitlines():
                if line.strip():
                    out.append(f"    /// {line}")
            out.append(f"    {_writer_type(field, types)} {field.name} = {_writer_default(field)};")
        if block.entry_fields:
            entry = _entry_struct(block.entry_name or f"{name}_ENTRY")
            out += [
                f"    /// The entries. store() writes STRIDE and COUNT from the",
                f"    /// vector's size -- they are never supplied.",
                f"    const std::vector<{entry}>& entries;",
            ]
        elif _is_blob(block, layout):
            out += [
                "    /// The byte run. What it means is not this layer's business: the",
                "    /// slicing comes from a sizes array elsewhere.",
                "    const ::IFE::BYTE* bytes = nullptr;",
                "    ::IFE::Size        count = 0;",
            ]
        out.append("};")


def _emit_validation_hooks(out: list[str], layout: LayoutResult) -> None:
    """The dispatch point for the optional conformance layer, present from day one."""
    out += [
        "",
        "/// The optional, runtime-attached spec-conformance layer.",
        "///",
        "/// The conformance layer implements what sits behind these pointers; this is the call site,",
        "/// and it is emitted now because adding a dispatch point later would break",
        "/// the ABI. Null when no layer is attached, which is what a shipped product",
        "/// runs: the cost is one predictable branch per store, never a search.",
        "///",
        "/// Borrowed from Vulkan: a separate library that need not be linked,",
        "/// attachment decided once at writer creation, diagnostics through a",
        "/// caller-owned string sink so the layer never owns I/O policy, and a",
        "/// `next` pointer so a future tracing layer composes rather than competes.",
        "/// Not borrowed: the loader, trampolines and manifest discovery.",
        "struct ValidationHooks {",
        "    const ValidationHooks* next = nullptr;",
        "",
        "    /// Where a diagnostic goes, if any. The layer formats; the caller",
        "    /// decides what I/O means. Point it at a string the caller owns:",
        "    /// each report replaces its contents, so clear it before a store to",
        "    /// detect whether one fired. Null to stay silent -- the Status still",
        "    /// carries the failure.",
        "    std::string* diagnostic = nullptr;",
        "",
        "    // One per block. Each receives the same CreateInfo and target offset",
        "    // store() was given -- the layer validates at the API boundary, as a",
        "    // Vulkan layer does, never against generated internals.",
    ]
    for name in layout.blocks:
        out.append(
            f"    Status (*{name})(const {_create_info(name)}&, ::IFE::Offset,"
            f" const ValidationHooks*) = nullptr;"
        )
    out.append("};")


def _writer_signature(name: str, declaration: bool) -> tuple[str, str]:
    """(size_of, store) signatures.

    The declaration carries `[[nodiscard]]` and defaults `__hooks`; the
    definition may do neither -- an attribute after `inline` is not a place the
    grammar allows one, and a default argument may be stated once.
    """
    info = _create_info(name)
    attrs = "[[nodiscard]] " if declaration else ""
    default = " = nullptr" if declaration else ""
    indent = (" " * len("Status store(") if declaration
              else " " * len("IFE_BLOCKS_LINKAGE Status store("))
    return (
        f"{attrs}::IFE::Size size_of(const {info}& __info) noexcept",
        f"Status store(::IFE::BYTE* __base, ::IFE::Offset __offset, const {info}& __info,\n"
        f"{indent}const ValidationHooks* __hooks{default}) noexcept",
    )


def _emit_writer_decls(out: list[str], layout: LayoutResult) -> None:
    for name, block in layout.blocks.items():
        size_of, store = _writer_signature(name, declaration=True)
        out.append("")
        out.append(f"// ---- {name} ----")
        if block.entry_fields:
            out.append("/// Header plus `count` entries at the stride this build writes.")
        elif _is_blob(block, layout):
            out.append("/// Header plus the byte run.")
        else:
            out.append("/// The header. A payload the schema does not describe -- IMAGE_BYTES'")
            out.append("/// label and stream, TILE_PIXEL_DATA -- is the runtime's to place.")
        out.append(f"{size_of};")
        out.append("/// Writes the block, then validates what it wrote. The machine-written")
        out.append("/// fields (VALIDATION, RECOVERY, MAGIC, STRIDE, COUNT) are never taken")
        out.append("/// from the caller.")
        out.append(f"{store};")


def _emit_pairs_writer(
    out: list[str], name: str, block: Any, layout: LayoutResult
) -> None:
    """The attribute blocks' writers: sizes array and packed byte run, both
    derived from one key/value pair vector.

    The consumer hands over the pairs once; the slicing cannot drift because
    it is derived here, not supplied. Two blocks, one payload -- the same
    shape the retired hand-written layer had (STORE_ATTRIBUTES_SIZES and
    STORE_ATTRIBUTES_BYTES both took the semantic Attributes).
    """
    vt = f"::IFE::blocks::{name}"
    entry = block.entry_name or f"{name}_ENTRY"
    size_of, store = _writer_signature(name, declaration=False)

    # Run before a byte is written, by both writers: the two blocks share one
    # payload, so a payload that disagrees with itself is wrong in both.
    guard = [
        "    // The payload must agree with its own KIND before anything is",
        "    // written. Dropping a caller's data silently is the failure this",
        "    // prevents; see attribute_payload_agrees and attribute_payload_fits.",
        "    for (const auto& __e : __info.entries)",
        "        if (!attribute_payload_agrees(__e) || !attribute_payload_fits(__e))",
        f"            return {{Check::BAD_NESTED_VALUE, {name}::type, \"KIND\",",
        "                    static_cast<std::uint64_t>(__e.KIND), 0, __offset};",
        "",
    ]

    out.append("")
    out.append(f"// ---- {name} ----")
    out.append("")
    out.append(f"IFE_BLOCKS_LINKAGE {size_of} {{")
    if block.entry_fields:  # ATTRIBUTE_SIZES: n entries of the fixed stride
        out += [
            f"    return {vt}::header_size",
            f"         + __info.entries.size() * {vt}::{entry}::entry_size;",
            "}",
            "",
            f"IFE_BLOCKS_LINKAGE {store} {{",
        ] + guard + [
            "    // The machine-written prefix, in wire order.",
            f"    ::IFE::store<std::uint64_t>(__base + __offset + {vt}::offset::VALIDATION,",
            "                               __offset);",
            f"    ::IFE::store<std::uint16_t>(__base + __offset + {vt}::offset::RECOVERY,",
            f"                               static_cast<std::uint16_t>({name}::recovery));",
            f"    ::IFE::store<std::uint16_t>(__base + __offset + {vt}::offset::STRIDE,",
            f"                               {vt}::{entry}::entry_size);",
            f"    ::IFE::store<std::uint32_t>(__base + __offset + {vt}::offset::COUNT,",
            "                               static_cast<std::uint32_t>(__info.entries.size()));",
            "",
            "    // One entry per attribute: the sizes that slice the packed run below.",
            f"    ::IFE::BYTE* __entry = __base + __offset + {vt}::header_size;",
            "    for (std::size_t __i = 0; __i < __info.entries.size();",
            f"         ++__i, __entry += {vt}::{entry}::entry_size) {{",
            "        const auto& __e = __info.entries[__i];",
            f"        ::IFE::store<std::uint16_t>(__entry + {vt}::{entry}::offset::KEY_SIZE,",
            "                                   static_cast<std::uint16_t>(__e.key.size()));",
            f"        ::IFE::store<std::uint32_t>(__entry + {vt}::{entry}::offset::VALUE_SIZE,",
            "                                   static_cast<std::uint32_t>(attribute_value_bytes(__e)));",
            f"        ::IFE::store<std::uint8_t>(__entry + {vt}::{entry}::offset::KIND,",
            "                                   static_cast<std::uint8_t>(__e.KIND));",
            "    }",
        ]
    else:  # ATTRIBUTE_BYTES: key bytes then value bytes, no separators
        out += [
            "    ::IFE::Size __total = 0;",
            "    for (const auto& __e : __info.entries)",
            "        __total += __e.key.size() + attribute_value_bytes(__e);",
            f"    return {vt}::header_size + __total;",
            "}",
            "",
            f"IFE_BLOCKS_LINKAGE {store} {{",
        ] + guard + [
            "    ::IFE::Size __total = 0;",
            "    for (const auto& __e : __info.entries)",
            "        __total += __e.key.size() + attribute_value_bytes(__e);",
            "    // The machine-written prefix, in wire order.",
            f"    ::IFE::store<std::uint64_t>(__base + __offset + {vt}::offset::VALIDATION,",
            "                               __offset);",
            f"    ::IFE::store<std::uint16_t>(__base + __offset + {vt}::offset::RECOVERY,",
            f"                               static_cast<std::uint16_t>({name}::recovery));",
            f"    ::IFE::store<std::uint32_t>(__base + __offset + {vt}::offset::COUNT,",
            "                               static_cast<std::uint32_t>(__total));",
            "",
            "    // Key then value, no separators: the sizes array is the slicing.",
            f"    ::IFE::BYTE* __p = __base + __offset + {vt}::header_size;",
            "    for (const auto& __e : __info.entries) {",
            "        std::memcpy(__p, __e.key.data(), __e.key.size());",
            "        __p += __e.key.size();",
            "        if (__e.KIND == ::IFE::constants::AttributeKinds::ATTRIBUTE_NESTED) {",
            "            // File offsets, not text: an edge the schema cannot describe,",
            "            // because a points_to lives on a field and these live in an",
            "            // opaque run whose length is data. They are written in the",
            "            // format's ordinary form -- absolute, 64-bit -- so nothing",
            "            // here needs a base to resolve one.",
            "            for (const ::IFE::Offset __n : __e.nested) {",
            "                ::IFE::store<std::uint64_t>(__p, __n);",
            "                __p += NESTED_OFFSET_SIZE;",
            "            }",
            "        } else {",
            "            std::memcpy(__p, __e.value.data(), __e.value.size());",
            "            __p += __e.value.size();",
            "        }",
            "    }",
        ]
    out += [
        "",
        "    // Structural validation is unconditional and inline: a few integer",
        "    // compares over what was just written.",
        f"    const {name} __written{{__base, __offset,",
        "                            __offset + size_of(__info), VERSION_WRITTEN};",
        "    if (const Status __status = __written.validate(); !__status) return __status;",
        "",
        "    // Spec conformance, only when a layer is attached.",
        f"    if (__hooks != nullptr && __hooks->{name} != nullptr)",
        f"        return __hooks->{name}(__info, __offset, __hooks);",
        "    return {};",
        "}",
    ]


def _emit_writer_defs(
    out: list[str], layout: LayoutResult, types: dict[str, Any]
) -> None:
    for name, block in layout.blocks.items():
        if block.from_pairs:
            _emit_pairs_writer(out, name, block, layout)
            continue
        primitive = layout.primitives[block.primitive]
        vt = f"::IFE::blocks::{name}"
        entry_type = block.entry_name or f"{name}_ENTRY"
        size_of, store = _writer_signature(name, declaration=False)

        out.append("")
        out.append(f"// ---- {name} ----")
        out.append("")
        out.append(f"IFE_BLOCKS_LINKAGE {size_of} {{")
        if block.entry_fields:
            out.append(f"    return {vt}::header_size")
            out.append(
                f"         + __info.entries.size() * {vt}::{entry_type}::entry_size;"
            )
        elif _is_blob(block, layout):
            out.append(f"    return {vt}::header_size + __info.count;")
        else:
            out.append("    (void)__info;")
            out.append(f"    return {vt}::header_size;")
        out.append("}")

        out.append("")
        out.append(f"IFE_BLOCKS_LINKAGE {store} {{")
        out.append("    // The machine-written prefix, in wire order.")
        for field in primitive.fields:
            if field.name not in _PRIMITIVE_FIELDS:
                raise SpecError(
                    f"primitive {block.primitive!r} declares field {field.name!r}, which the "
                    f"writer emitter does not know how to fill; teach _PRIMITIVE_FIELDS "
                    f"what supplies it before adding it to the schema"
                )
            if field.kind == "constant":
                value = f"::IFE::constants::{field.constant}"
            elif field.name == "VALIDATION":
                # VALIDATION stores its own position. At the block start
                # (offset 0) that is the handle's offset; as a backward
                # trailer it sits at a fixed displacement behind the anchor
                # (TILE_FRAME's -5), and storing the anchor would
                # self-reference the stream the frame precedes, not the
                # frame — the exact off-by-5 the runtime recovery scan
                # depends on catching (load_u40(position) == position).
                validation_at = {f.name: f for f in primitive.fields}["VALIDATION"].offset
                if validation_at == 0:
                    value = "__offset"
                else:
                    value = f"__offset + {vt}::offset::VALIDATION"
            elif field.name == "RECOVERY":
                # _write_expression supplies the cast to the underlying type.
                value = f"{name}::recovery"
            elif field.name == "STRIDE":
                value = f"{vt}::{entry_type}::entry_size"
            else:  # COUNT
                # Entry arrays size themselves; byte blobs carry a count.
                if block.entry_fields:
                    value = f"static_cast<{field.cpp_type}>(__info.entries.size())"
                else:
                    value = f"static_cast<{field.cpp_type}>(__info.count)"
            # Through the block's own table: the fold duplicated the machine-
            # written prefix's offsets into every block, and the shared readers
            # use the same constants, so writer and reader cannot name
            # different bytes.
            out.append(
                "    "
                + _write_expression(
                    field, name, value, types, "__base + __offset"
                )
            )

        caller = _caller_fields(block, layout)
        if caller:
            out.append("")
            out.append("    // What only the caller knows.")
            for field in caller:
                out.append(
                    "    "
                    + _write_expression(
                        field, name, f"__info.{field.name}", types, "__base + __offset"
                    )
                )

        if block.entry_fields:
            out += [
                "",
                "    // Entries step by the stride this build writes, which is what was",
                "    // just stored in STRIDE -- a reader steps by the stride it finds.",
                f"    ::IFE::BYTE* __entry = __base + __offset + {vt}::header_size;",
                "    for (std::size_t __i = 0; __i < __info.entries.size();",
                f"         ++__i, __entry += {vt}::{entry_type}::entry_size) {{",
                f"        const {_entry_struct(block.entry_name or name + '_ENTRY')}&"
                " __e = __info.entries[__i];",
            ]
            for field in block.entry_fields:
                if field.kind == "constant":
                    continue
                out.append(
                    "        "
                    + _write_expression(
                        field, f"{name}::{entry_type}", f"__e.{field.name}", types, "__entry"
                    )
                )
            out.append("    }")
        elif _is_blob(block, layout):
            out += [
                "",
                "    if (__info.bytes != nullptr && __info.count != 0)",
                f"        std::memcpy(__base + __offset + {vt}::header_size,",
                "                    __info.bytes, __info.count);",
            ]

        out += [
            "",
            "    // Structural validation is unconditional and inline: a few integer",
            "    // compares over what was just written. __size is the block's own end,",
            "    // which is all validate() looks at.",
            f"    const {name} __written{{__base, __offset,",
            "                            __offset + size_of(__info), VERSION_WRITTEN};",
            "    if (const Status __status = __written.validate(); !__status) return __status;",
            "",
            "    // Spec conformance, only when a layer is attached.",
            f"    if (__hooks != nullptr && __hooks->{name} != nullptr)",
            f"        return __hooks->{name}(__info, __offset, __hooks);",
            "    return {};",
            "}",
        ]


def emit_blocks_header(
    layout: LayoutResult,
    types: dict[str, Any],
    document: dict[str, Any],
    header: dict[str, Any],
    witness_hash: str,
) -> str:
    """IFE_Blocks.hpp — the whole generated C++ layer, one header.

    Constants, derived vtables, the block handles and their inline
    definitions, and the IrisCodec::Serialization consumer namespace are all
    emitted into this single file. The three-way namespace split inside is
    the generator's structure (one data kind per namespace); one file keeps
    the consumer's include surface to a single generated header, and every
    definition is inline so a consumer reaches the handles and writers with
    an include alone — no translation unit to compile, nothing to link.
    Inline definitions create no exported symbols, which is what keeps the
    export decision (the block layer stays out of the shared library's ABI)
    and the library's VISIBILITY_INLINES_HIDDEN keeps them out of the
    dynamic symbol table.
    """
    version = header.get("version", {})
    out: list[str] = [
        _banner(header, witness_hash),
        "#ifndef IFE_Blocks_hpp",
        "#define IFE_Blocks_hpp",
        "",
        "#include <cstddef>",
        "#include <cstdint>",
        "#include <cstring>  // byte-array writers copy the payload wholesale",
        "#include <optional>",
        "#include <limits>",
        "#include <string>",
        "#include <vector>",
        "",
        '#include "IFE_Bytes.hpp"',
        "",
        "// The whole generated layer in one header: constants, derived",
        "// vtables, the block handles, and the IrisCodec::Serialization",
        "// consumer namespace at the end. Three headers were consolidated into",
        "// this one; the *definitions* are a separate translation unit,",
        "// IFE_Blocks.cpp, which is a different question and answered below.",
        "",
        "// Where the definitions come from.",
        "//",
        "// By default they are compiled once, in IFE_Blocks.cpp, and this header",
        "// declares them -- so a translation unit including it pays for the",
        "// declarations alone. Define IFE_HEADER_ONLY before including it and",
        "// that translation unit is folded in at the bottom of this file",
        "// instead, for a consumer that would rather link nothing.",
        "//",
        "// The linkage differs between the two: folded into many translation",
        "// units the definitions must be inline or the link sees each of them",
        "// several times; compiled once they must not be, or the object file",
        "// provides nothing to link against.",
        "#ifdef IFE_HEADER_ONLY",
        "#define IFE_BLOCKS_LINKAGE inline",
        "#else",
        "#define IFE_BLOCKS_LINKAGE",
        "#endif",
        "",
        "namespace IFE {",
        f"inline constexpr unsigned IFE_SCHEMA_VERSION_MAJOR = {version.get('major', 0)};",
        f"inline constexpr unsigned IFE_SCHEMA_VERSION_MINOR = {version.get('minor', 0)};",
        "",
    ]

    # ---- constants ----
    _emit_constants_body(out, document, types)
    out.append("")

    # ---- blocks: the write API first, then the handles ----
    out.append("namespace blocks {")

    out.extend(_STATUS_PREAMBLE.strip("\n").splitlines())

    # The write API first: a programmer reads the payloads and entry points
    # before the layout internals.
    out += [
        "",
        "// ---- writers: payloads and entry points ----",
        "// What a caller supplies, and the two functions that consume it. The",
        "// machine-written fields never appear here: a CreateInfo carries only what",
        "// the generator cannot derive.",
        "",
        "/// The version a writer stamps and validates against: what this build knows.",
        "inline constexpr std::uint32_t VERSION_WRITTEN =",
        "    (::IFE::IFE_SCHEMA_VERSION_MAJOR << 16) | ::IFE::IFE_SCHEMA_VERSION_MINOR;",
    ]
    _emit_create_infos(out, layout, types)
    _emit_validation_hooks(out, layout)
    _emit_writer_decls(out, layout)

    out.append("")
    out.append("// Forward declarations: offset fields return handles to other blocks, and")
    out.append("// the reference graph has cycles no ordering would resolve.")
    for name in layout.blocks:
        out.append(f"struct {name};")
    out.append("}  // namespace blocks")

    # Each block is self-contained: its layout table (machine-written prefix
    # included), its handle, and its accessors sit together.
    for name, block in layout.blocks.items():
        primitive = layout.primitives[block.primitive]
        out.append("")
        out.append(f"// ================= {name} =================")
        out.extend(_comment(block.description))
        out.append("namespace blocks {")
        out.append(f"struct {name} {{")
        _emit_folded_primitive(out, block, layout, types)
        out.append(f'    static constexpr char type[] = "{name}";')
        recovery_enum = _pascal("recovery_codes")
        if block.recovery_tag:
            out.append(f"    static constexpr ::IFE::constants::{recovery_enum} recovery =")
            out.append(f"        ::IFE::constants::{recovery_enum}::{block.recovery_tag};")
        # The block's layout table. The primitives' shared tables fold into
        # each block — generated duplication, like the accessors — so the
        # `vtables` namespace is gone and a block reads as one unit (the
        # retired hand-written layer kept the same tables inside each
        # struct).
        own = tuple(f for f in block.header_fields if f not in primitive.fields)
        chain_fields: list[FieldLayout] = []
        for prim in _primitive_chain(block, layout):
            inherited = layout.primitives[prim.extends].fields if prim.extends else ()
            chain_fields += [f for f in prim.fields if f not in inherited]
        out.extend(_emit_size_offset(chain_fields + list(own)))
        _emit_version_markers(out, "    ", "header_size", block.header_sizes)
        if block.from_sof is not None:
            out.append(
                f"    /// Fixed at byte 0; occupies the first {block.from_sof} B of the file."
            )
            out.append(f"    static constexpr std::size_t from_sof = {block.from_sof};")
        out.append("")
        out.append("    constexpr explicit operator bool() const noexcept { return fits(header_size); }")

        if block.entry_fields:
            entry = block.entry_name or f"{name}_ENTRY"
            out.append("")
            out.append(f"    /// One {entry}, addressed by the array's stored stride.")
            out.append(f"    struct {entry} {{")
            out.extend(_emit_size_offset(block.entry_fields, indent="        "))
            _emit_version_markers(out, "        ", "entry_size", block.entry_sizes)
            out += [
                "        const ::IFE::BYTE* __base    = nullptr;",
                "        ::IFE::Offset      __offset  = 0;",
                "        ::IFE::Size        __size    = 0;   ///< total file size",
                "        std::uint16_t      __stride  = 0;   ///< as written, not as compiled",
                "        std::uint32_t      __version = 0;",
            ]
            marks = _version_boundaries(block.entry_fields)
            for index, member in enumerate(_entry_members(name, block, types)):
                out.append("")
                _declare(out, member, indent="        ")
                if index in marks:
                    out.append(f"        // Version {marks[index]} ends here.")
                    out.append("        // -------------------------------------------------------")
            out.append("    };")
            out.append("")
            out.append("    /// Entry `i`, stepped by the STRIDE the encoder wrote — never by the")
            out.append("    /// size this build was compiled with.")
            out.append(f"    [[nodiscard]] {entry} entry(std::uint32_t __i) const noexcept;")
            out.append("    [[nodiscard]] ::IFE::Offset entries_begin() const noexcept;")
        elif _is_blob(block, layout):
            out.append("")
            out.append("    /// The whole byte run. Its interpretation is not this layer's")
            out.append("    /// business: slicing comes from a sizes array elsewhere and the")
            out.append("    /// character encoding is normative prose.")
            out.append("    [[nodiscard]] ::IFE::ByteSpan bytes() const noexcept;")
            out.append("    [[nodiscard]] ::IFE::Offset entries_begin() const noexcept;")

        marks = _version_boundaries(own)
        for index, member in enumerate(_block_members(name, block, layout, types)):
            out.append("")
            _declare(out, member)
            if index in marks:
                out.append(f"    // Version {marks[index]} ends here.")
                out.append("    // ---------------------------------------------------------------")
        out.append("")
        out.append("    /// Convenience: deep validation from a fresh path.")
        out.append("    [[nodiscard]] Status validate_deep() const noexcept;")
        out.append("};")
        out.append("}  // namespace blocks")

    out += [
        "",
        "}  // namespace IFE",
        "",
    ]

    # ---- the consumer namespace, after the layer it re-exports ----
    _emit_serialization_body(out, layout, document)

    # The definitions, folded in only when the consumer asked for it. Last in
    # the file so everything it defines has been declared, and inside the
    # include guard so the nested include is a no-op on the way back.
    out += [
        "",
        "#ifdef IFE_HEADER_ONLY",
        '#include "IFE_Blocks.cpp"',
        "#endif",
        "",
        "#endif  // IFE_Blocks_hpp",
        "",
    ]
    return "\n".join(out)


def emit_blocks_source(
    layout: LayoutResult,
    types: dict[str, Any],
    header: dict[str, Any],
    witness_hash: str,
) -> str:
    """IFE_Blocks.cpp -- the block layer's definitions, compiled once.

    Compiled as its own translation unit by default; included by
    IFE_Blocks.hpp when a consumer defines IFE_HEADER_ONLY. The guard below
    makes the second case safe, and IFE_BLOCKS_LINKAGE (declared in the
    header) is what makes the definitions inline in that case and not in this
    one.

    Not exported either way. The library builds with hidden visibility, and
    tests/exported_symbols.cmake fails the build if an IFE:: symbol reaches
    the dynamic table -- so moving these out of the header changes what is
    compiled, never what is in the ABI.
    """
    out: list[str] = [
        _banner(header, witness_hash),
        "#ifndef IFE_Blocks_cpp",
        "#define IFE_Blocks_cpp",
        "",
        "// A no-op when this file was reached from the header's IFE_HEADER_ONLY",
        "// fold, which is the point: the same source serves both ways of",
        "// consuming the layer.",
        '#include "IFE_Blocks.hpp"',
        "",
        "namespace IFE {",
        "namespace blocks {",
    ]
    _emit_inline_definitions(out, layout, types)
    out += [
        "",
        "}  // namespace blocks",
        "}  // namespace IFE",
        "",
        "#endif  // IFE_Blocks_cpp",
        "",
    ]
    return "\n".join(out)


def _emit_inline_definitions(
    out: list[str], layout: LayoutResult, types: dict[str, Any]
) -> None:
    """The block layer's definitions, emitted inline into the header.

    Every definition is `inline` so any number of translation units may
    include the header; the block layer is header-only by design, which is
    what lets a consumer reach store()/size_of() with an include alone.
    """
    for name, block in layout.blocks.items():
        out.append("")
        out.append(f"// ---- {name} ----")

        # The folded machine-written prefix: one definition per owning block
        # now that the primitives are inlined (the JSON remains the single
        # source of the shared accessors' bodies).
        for prim in _primitive_chain(block, layout):
            inherited = layout.primitives[prim.extends].fields if prim.extends else ()
            introduced = tuple(f for f in prim.fields if f not in inherited)
            for member in _field_members(introduced, types):
                out.append("")
                out.append(
                    f"IFE_BLOCKS_LINKAGE {member.ret} {name}::{member.name}"
                    f"({member.params}) {member.quals} {{"
                )
                out.extend(member.body)
                out.append("}")

        if block.entry_fields:
            entry = block.entry_name or f"{name}_ENTRY"
            for member in _entry_members(name, block, types):
                out.append("")
                out.append(
                    f"IFE_BLOCKS_LINKAGE {member.ret} {name}::{entry}::{member.name}"
                    f"({member.params}) {member.quals} {{"
                )
                out.extend(member.body)
                out.append("}")
            out.append("")
            out.append(f"IFE_BLOCKS_LINKAGE ::IFE::Offset {name}::entries_begin() const noexcept {{")
            out.append("    return entries_at(header_size);")
            out.append("}")
            out.append("")
            out.append(
                f"IFE_BLOCKS_LINKAGE {name}::{entry} {name}::entry(std::uint32_t __i) const noexcept {{"
            )
            out.append(f"    return {entry}{{__base,")
            out.append("                 entries_begin() + static_cast<::IFE::Offset>(__i) * stride(),")
            out.append("                 __size, stride(), __version};")
            out.append("}")
        elif _is_blob(block, layout):
            out.append("")
            out.append(f"IFE_BLOCKS_LINKAGE ::IFE::Offset {name}::entries_begin() const noexcept {{")
            out.append("    return entries_at(header_size);")
            out.append("}")
            out.append("")
            out.append(f"IFE_BLOCKS_LINKAGE ::IFE::ByteSpan {name}::bytes() const noexcept {{")
            out.append("    return {__base + entries_begin(), count()};")
            out.append("}")

        for member in _block_members(name, block, layout, types):
            out.append("")
            out.append(
                f"IFE_BLOCKS_LINKAGE {member.ret} {name}::{member.name}"
                f"({member.params}) {member.quals} {{"
            )
            out.extend(member.body)
            out.append("}")

        out.append("")
        out.append(f"IFE_BLOCKS_LINKAGE Status {name}::validate_deep() const noexcept {{")
        out.append("    VisitPath __path;")
        out.append("    return validate_deep(__path);")
        out.append("}")

    out.append("")
    out.append("// ================= writers =================")
    _emit_writer_defs(out, layout, types)


# ---------------------------------------------------------------------------
# Validation layer. The optional, runtime-attachable spec-conformance
# checks, emitted from the normative clauses in the schema so a diagnostic and
# the published document cite the same source.
# ---------------------------------------------------------------------------


def _clauses(fields: tuple[FieldLayout, ...]) -> list[FieldLayout]:
    return [f for f in fields if f.conformance]


def _requirement(block: str, field: FieldLayout) -> str:
    """The sentence a violation prints, in v1's style: name the clause, then
    cite the section that states it."""
    c = field.conformance or {}
    # The stable clause id, not a section number. A number is positional: a
    # renumbering that lands on another real section makes the diagnostic point
    # confidently at the wrong requirement, and nothing detects it. The id is
    # what the specification anchors, and --validate proves it resolves.
    text = (
        f"{block}.{field.name} {c.get('level', 'shall')} "
        f"{c.get('requirement', 'satisfy the specification')}. "
        f"Per the IFE specification, clause {c.get('clause', '?')}."
    )
    return text.replace('"', "'")


def _check_lines(block: str, field: FieldLayout, value: str, types: dict[str, Any]) -> list[str]:
    """One clause, as C++. Every branch here is a closed-vocabulary predicate;
    there is deliberately no expression syntax to evaluate."""
    c = field.conformance or {}
    message = _requirement(block, field)
    fail = [
        f'        __report(__hooks, "{message}");',
        f'        return {{Check::CONFORMANCE, "{block}", "{field.name}",',
        f"                static_cast<std::uint64_t>({value}), 0, __at}};",
    ]
    out: list[str] = []
    if "minimum" in c:
        out += [f"    if ({value} < {c['minimum']}) {{"] + fail + ["    }"]
    if "maximum" in c:
        out += [f"    if ({value} > {c['maximum']}) {{"] + fail + ["    }"]
    if c.get("non_null"):
        out += [f"    if ({value} == ::IFE::constants::NULL_OFFSET) {{"] + fail + ["    }"]
    if c.get("enum_member"):
        enum = _pascal(field.type_name)
        out += [f"    if (!is_member(static_cast<::IFE::constants::{enum}>({value}))) {{"] + fail + ["    }"]
    return out


def emit_validation_source(
    layout: LayoutResult, constants_doc: dict[str, Any], types: dict[str, Any],
    header: dict[str, Any], witness_hash: str
) -> str:
    """IFE_Validation.cpp — the conformance layer behind the writers' hook."""
    out: list[str] = [
        _banner(header, witness_hash),
        "// The optional layer: attachable at runtime,",
        "// costing a null check when absent, and free to be verbose because it",
        "// never runs in a shipped product's hot path. Every check below is",
        "// generated from a normative clause in spec/ife_fields.json, so a",
        "// diagnostic and the published specification cite one source.",
        "",
        '#include "IFE_Validation.hpp"',
        "",
        "namespace IFE {",
        "namespace blocks {",
        "namespace {",
        "",
        "void __report(const ValidationHooks* __hooks, const char* __message) noexcept {",
        "    // The layer formats; the caller decides what I/O means. Silent when",
        "    // no sink was registered -- the Status still carries the failure.",
        "    if (__hooks != nullptr && __hooks->diagnostic != nullptr)",
        "        *__hooks->diagnostic = __message;",
        "}",
    ]

    # Membership predicates, one per enum group the clauses reference.
    referenced: dict[str, None] = {}
    for name, block in layout.blocks.items():
        for field in _clauses(block.header_fields) + _clauses(block.entry_fields):
            if (field.conformance or {}).get("enum_member"):
                referenced[field.type_name] = None
    for group_name in referenced:
        group = constants_doc.get(group_name, {})
        members = [
            member
            for entries in group.get("ife_version", {}).values()
            for member in entries
        ]
        enum = _pascal(group_name)
        out += [
            "",
            f"/// Whether a value names a declared member of {group_name}.",
            f"[[nodiscard]] bool is_member(::IFE::constants::{enum} __v) noexcept {{",
            "    switch (__v) {",
        ]
        out += [f"        case ::IFE::constants::{enum}::{m}:" for m in members]
        out += ["            return true;", "    }", "    return false;", "}"]

    out += ["", "}  // namespace"]

    # One check per block carrying clauses.
    checked: list[str] = []
    for name, block in layout.blocks.items():
        header_clauses = _clauses(block.header_fields)
        entry_clauses = _clauses(block.entry_fields)
        if not header_clauses and not entry_clauses:
            continue
        checked.append(name)
        info = _create_info(name)
        out += [
            "",
            f"// ---- {name} ----",
            f"Status check_{name}(const {info}& __info, ::IFE::Offset __at,",
            "                    const ValidationHooks* __hooks) noexcept {",
        ]
        for field in header_clauses:
            out += _check_lines(name, field, f"__info.{field.name}", types)

        if entry_clauses:
            entry = _entry_struct(block.entry_name or f"{name}_ENTRY")
            out += [
                "",
                "    for (std::size_t __i = 0; __i < __info.entries.size(); ++__i) {",
                f"        const {entry}& __e = __info.entries[__i];",
            ]
            for field in entry_clauses:
                if (field.conformance or {}).get("ordering"):
                    continue
                out += ["    " + line for line in
                        _check_lines(f"{name}.{block.entry_name}", field, f"__e.{field.name}", types)]
            out.append("    }")

            # Ordering is the one clause that is about the sequence rather than
            # a value, so it gets its own pass over the entries.
            for field in entry_clauses:
                order = (field.conformance or {}).get("ordering")
                if not order:
                    continue
                message = _requirement(f"{name}.{block.entry_name}", field)
                out += [
                    "",
                    f"    for (std::size_t __i = 1; __i < __info.entries.size(); ++__i) {{",
                    f"        if (!(__info.entries[__i].{field.name} >"
                    f" __info.entries[__i - 1].{field.name})) {{",
                    f'            __report(__hooks, "{message}");',
                    f'            return {{Check::CONFORMANCE, "{name}", "{field.name}",',
                    f"                    static_cast<std::uint64_t>(__i), 0, __at}};",
                    "        }",
                    "    }",
                ]

        out += [
            "",
            "    // Layers chain, as Vulkan's do: this one passed, so ask the next.",
            f"    if (__hooks != nullptr && __hooks->next != nullptr && __hooks->next->{name} != nullptr)",
            f"        return __hooks->next->{name}(__info, __at, __hooks->next);",
            "    return {};",
            "}",
        ]

    out += [
        "",
        "const ValidationHooks& conformance_layer() noexcept {",
        "    static const ValidationHooks __layer = [] {",
        "        ValidationHooks __h{};",
    ]
    out += [f"        __h.{name} = &check_{name};" for name in checked]
    out += [
        "        return __h;",
        "    }();",
        "    return __layer;",
        "}",
        "",
        "}  // namespace blocks",
        "}  // namespace IFE",
        "",
    ]
    return "\n".join(out)


def emit_validation_header(
    layout: LayoutResult, header: dict[str, Any], witness_hash: str
) -> str:
    """IFE_Validation.hpp — how an application attaches the layer."""
    return "\n".join([
        _banner(header, witness_hash),
        "#ifndef IFE_Validation_hpp",
        "#define IFE_Validation_hpp",
        "",
        '#include "IFE_Blocks.hpp"',
        "",
        "namespace IFE {",
        "namespace blocks {",
        "",
        "/// The spec-conformance layer.",
        "///",
        "/// Attach it once, at writer creation, by passing it to store():",
        "///",
        "///     std::string why;",
        "///     ValidationHooks hooks = conformance_layer();",
        "///     hooks.diagnostic = &why;",
        "///     store(base, offset, info, &hooks);",
        "///",
        "/// Detached -- the default -- a store costs one null check and the",
        "/// structural validate(). Attached, every `shall` clause in the schema is",
        "/// enforced and each diagnostic cites the section that states it.",
        "///",
        "/// A development tool, not a production dependency: it lives in its own",
        "/// library (IrisFileExtensionValidation) so an application links it only",
        "/// when it wants it, exactly as a Vulkan validation layer is.",
        "///",
        "/// Copy the returned struct before setting `diagnostic` or `next` -- the",
        "/// layer itself is shared and immutable.",
        "[[nodiscard]] const ValidationHooks& conformance_layer() noexcept;",
        "",
        "}  // namespace blocks",
        "}  // namespace IFE",
        "",
        "#endif  // IFE_Validation_hpp",
        "",
    ])


def _emit_serialization_body(
    out: list[str], layout: LayoutResult, document: dict[str, Any]
) -> None:
    """The `IrisCodec::Serialization` re-export: the consumer-facing write API.

    One namespace for the whole write surface — block handles, payloads,
    store()/size_of(), enumerations, sentinels — so a consumer never visits
    the generated layer's three-way internal split (constants / vtables /
    blocks), which is the generator's structure, not the consumer's. Emitted
    into the merged IFE_Blocks.hpp, after the layer it re-exports, so a
    schema change propagates here on the next run.
    """
    out += [
        "namespace IrisCodec {",
        "namespace Serialization {",
        "",
        "// The enumerations, by schema group.",
        "// A consumer names the members (Serialization::TileEncodings::TILE_ENCODING_JPEG)",
        "// without knowing they are generated into IFE::constants.",
    ]
    for group_name, group in constants_groups(document).items():
        if is_enum_group(group):
            out.append(f"using ::IFE::constants::{_pascal(group_name)};")

    out += [
        "",
        "// The sentinels and named values (NULL_OFFSET, MAGIC_BYTES, ...).",
    ]
    for group_name, group in value_groups(document).items():
        if group_name == "image_orientations":
            # The orientation constants duplicate the Iris-Headers
            # ImageOrientation enum a consumer already has (same names,
            # different types: half-precision bits there, decoded floats
            # here). Exporting both would make identical-looking names mean
            # different things — the opposite of foolproof. The generated
            # copies exist for the specification document, not for code.
            continue
        for _, entries in sorted(
            group.get("ife_version", {}).items(), key=lambda kv: version_key(kv[0])
        ):
            for name in entries:
                out.append(f"using ::IFE::constants::{name};")

    out += [
        "",
        "// The version this build writes. FILE_HEADER's EXTENSION_MAJOR/MINOR",
        "// default to these, so a file written without thinking about version",
        "// claims the layout its bytes actually have.",
        "using ::IFE::IFE_SCHEMA_VERSION_MAJOR;",
        "using ::IFE::IFE_SCHEMA_VERSION_MINOR;",
        "",
        "// The validation vocabulary store() reports through.",
        "using ::IFE::blocks::Check;",
        "using ::IFE::blocks::Status;",
        "using ::IFE::blocks::ValidationHooks;",
        "using ::IFE::blocks::VERSION_WRITTEN;",
        "",
        "// Every block, its payload, and its entry type, in schema order.",
        "// The handle carries header_size and recovery as statics, so the",
        "// vtables namespace never needs to be visited from consumer code.",
    ]
    for name, block in layout.blocks.items():
        out.append(f"using ::IFE::blocks::{name};")
        out.append(f"using ::IFE::blocks::{_create_info(name)};")
        # from_pairs blocks are included: their payload used to be a
        # std::pair, which needed no re-export, and is now a generated type.
        # Leaving them out published a CreateInfo whose payload type the
        # consumer namespace did not name -- the write API for attributes was
        # unusable through Serialization:: without reaching into IFE::blocks.
        if block.entry_fields:
            entry = _entry_struct(block.entry_name or f"{name}_ENTRY")
            out.append(f"using ::IFE::blocks::{entry};")

    out += [
        "",
        "",
        "// Reading and writing a nested attribute value in items rather than",
        "// bytes. The wire stores a byte length -- that is what lets a decoder",
        "// walk the packed run without interpreting any value -- and these are",
        "// how a caller works in the unit it actually thinks in.",
        "using ::IFE::blocks::NESTED_OFFSET_SIZE;",
        "using ::IFE::blocks::nested_count;",
        "using ::IFE::blocks::nested_offset;",
        "using ::IFE::blocks::nested_size_is_whole;",
        "using ::IFE::blocks::attribute_value_bytes;",
        "",
        "// The write entry points, one overload set per kind of work:",
        "//     size_of(payload)   -> bytes the block will occupy",
        "//     store(base, offset, payload, hooks = nullptr) -> Status",
        "// The payloads are the CreateInfos above; the machine-written fields",
        "// (VALIDATION, RECOVERY, MAGIC, STRIDE, COUNT) are never supplied.",
        "using ::IFE::blocks::size_of;",
        "using ::IFE::blocks::store;",
        "",
        "}  // namespace Serialization",
        "}  // namespace IrisCodec",
    ]
